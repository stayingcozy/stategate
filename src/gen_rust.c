static void add(GenSet *g, const char *path, SB *content, int scaffold) {
    if (g->n == g->cap) {
        g->cap = g->cap ? g->cap * 2 : 16;
        g->v = xrealloc(g->v, sizeof(GenFile) * (size_t)g->cap);
    }
    g->v[g->n].path = xstrdup(path);
    g->v[g->n].content = content->s;
    g->v[g->n].scaffold = scaffold;
    g->n++;
}

static void header(SB *b, const Model *m) {
    sb_printf(b, "// @generated by stategate from %s. Do not edit: change the model and run `stategate gen`.\n", m->path);
}

static const char *ev(const char *name) {
    /* Small rotating buffer of camel-cased event names for inline use. */
    static char *ring[8];
    static int i;
    i = (i + 1) % 8;
    free(ring[i]);
    ring[i] = upper_snake_to_camel(name);
    return ring[i];
}

static const char *state_name(const Model *m, const char *id) {
    State *s = model_state(m, id);
    return s ? s->name : "?";
}

static const char *initial_name(const Model *m) {
    for (int i = 0; i < m->n_states; i++)
        if (m->states[i].initial) return m->states[i].name;
    return "?";
}

static const char *rust_max(const char *arg) {
    if (!strcmp(arg, "u8")) return "u8::MAX";
    if (!strcmp(arg, "u16")) return "u16::MAX";
    if (!strcmp(arg, "u32")) return "u32::MAX";
    return "i32::MAX";
}

static const Invariant *clamp_for(const Model *m, const char *call) {
    for (int i = 0; i < m->n_invariants; i++)
        if (m->invariants[i].kind == INV_HAL_CLAMP && !strcmp(m->invariants[i].call, call)) return &m->invariants[i];
    return NULL;
}

static void gen_cargo(const Model *m, GenSet *g) {
    SB b;
    sb_init(&b);
    sb_printf(&b, "# @generated by stategate from %s. Do not edit: change the model and run `stategate gen`.\n", m->path);
    sb_printf(&b, "[package]\nname = \"%s\"\nversion = \"0.1.0\"\nedition = \"2021\"\npublish = false\n\n[dependencies]\n", m->id);
    add(g, "Cargo.toml", &b, 0);
}

static void gen_lib(const Model *m, GenSet *g) {
    SB b;
    sb_init(&b);
    header(&b, m);
    sb_puts(&b, "pub mod actions;\npub mod gen;\npub mod services;\n");
    add(g, "src/lib.rs", &b, 0);

    sb_init(&b);
    header(&b, m);
    sb_puts(&b, "pub mod fake;\npub mod hal;\npub mod machine;\n\npub use machine::{Event, Machine, Outcome, State};\n");
    add(g, "src/gen/mod.rs", &b, 0);

    sb_init(&b);
    header(&b, m);
    for (int i = 0; i < m->n_actions; i++) sb_printf(&b, "pub mod %s;\n", m->actions[i].id);
    add(g, "src/actions/mod.rs", &b, 0);

    sb_init(&b);
    header(&b, m);
    for (int i = 0; i < m->n_services; i++) sb_printf(&b, "pub mod %s;\n", m->services[i].id);
    add(g, "src/services/mod.rs", &b, 0);
}

static void gen_hal(const Model *m, GenSet *g) {
    SB b;
    sb_init(&b);
    header(&b, m);
    sb_puts(&b,
            "\n/// Hardware abstraction layer. Implement it once for the real board and once\n"
            "/// for tests (see `fake.rs`). Node logic never sees this trait directly.\n"
            "pub trait Hal {\n"
            "    fn now_ms(&self) -> u64;\n"
            "    fn log(&mut self, msg: &str);\n");
    for (int i = 0; i < m->n_hal; i++)
        sb_printf(&b, "    fn %s(&mut self, value: %s);\n", m->hal[i].call, m->hal[i].arg);
    sb_puts(&b, "}\n\n");

    for (int i = 0; i < m->n_hal; i++) {
        const Invariant *c = clamp_for(m, m->hal[i].call);
        if (!c) continue;
        char *up = xstrdup(m->hal[i].call);
        for (char *p = up; *p; p++) *p = (char)(*p >= 'a' && *p <= 'z' ? *p - 32 : *p);
        sb_printf(&b, "/// Locked by %s.\npub const %s_MAX: %s = %ld;\n\n", c->id, up, m->hal[i].arg, c->max);
        free(up);
    }

    sb_puts(&b,
            "/// The only HAL handle node logic receives. Locked safety limits are enforced\n"
            "/// here, in generated code, so no action can exceed them.\n"
            "pub struct SafeHal<H: Hal> {\n    inner: H,\n}\n\n"
            "impl<H: Hal> SafeHal<H> {\n"
            "    pub fn new(inner: H) -> Self {\n        Self { inner }\n    }\n\n"
            "    pub fn now_ms(&self) -> u64 {\n        self.inner.now_ms()\n    }\n\n"
            "    pub fn log(&mut self, msg: &str) {\n        self.inner.log(msg)\n    }\n");
    for (int i = 0; i < m->n_hal; i++) {
        const HalCall *h = &m->hal[i];
        const Invariant *c = clamp_for(m, h->call);
        sb_puts(&b, "\n");
        if (c) {
            char *up = xstrdup(h->call);
            for (char *p = up; *p; p++) *p = (char)(*p >= 'a' && *p <= 'z' ? *p - 32 : *p);
            sb_printf(&b, "    /// @invariant %s: value is clamped to at most %ld.\n", c->id, c->max);
            sb_printf(&b, "    pub fn %s(&mut self, value: %s) {\n", h->call, h->arg);
            sb_printf(&b, "        let value = if value > %s_MAX { %s_MAX } else { value };\n", up, up);
            sb_printf(&b, "        self.inner.%s(value)\n    }\n", h->call);
            free(up);
        } else {
            sb_printf(&b, "    pub fn %s(&mut self, value: %s) {\n        self.inner.%s(value)\n    }\n", h->call, h->arg, h->call);
        }
    }
    sb_puts(&b, "}\n");
    add(g, "src/gen/hal.rs", &b, 0);
}

static void gen_fake(const Model *m, GenSet *g) {
    SB b;
    sb_init(&b);
    header(&b, m);
    sb_puts(&b,
            "//! Fake hardware for tests and simulation on a PC.\n\n"
            "use std::cell::RefCell;\nuse std::rc::Rc;\n\nuse super::hal::Hal;\n\n"
            "/// What the fake recorded. Tests keep a handle to it via `FakeHal::new()`.\n"
            "#[derive(Default, Debug)]\n"
            "pub struct Probe {\n"
            "    pub now_ms: u64,\n"
            "    /// (call name, value) for every HAL call, in order.\n"
            "    pub calls: Vec<(String, i64)>,\n"
            "    /// (time, message) for every log line, in order.\n"
            "    pub logs: Vec<(u64, String)>,\n"
            "}\n\n"
            "impl Probe {\n"
            "    /// The last value passed to `call`, if any.\n"
            "    pub fn last(&self, call: &str) -> Option<i64> {\n"
            "        self.calls.iter().rev().find(|(c, _)| c == call).map(|(_, v)| *v)\n"
            "    }\n"
            "}\n\n"
            "#[derive(Clone, Default)]\n"
            "pub struct FakeHal {\n    probe: Rc<RefCell<Probe>>,\n}\n\n"
            "impl FakeHal {\n"
            "    pub fn new() -> (Self, Rc<RefCell<Probe>>) {\n"
            "        let fake = Self::default();\n"
            "        let probe = fake.probe.clone();\n"
            "        (fake, probe)\n"
            "    }\n"
            "}\n\n"
            "impl Hal for FakeHal {\n"
            "    fn now_ms(&self) -> u64 {\n        self.probe.borrow().now_ms\n    }\n\n"
            "    fn log(&mut self, msg: &str) {\n"
            "        let mut p = self.probe.borrow_mut();\n"
            "        let now = p.now_ms;\n"
            "        p.logs.push((now, msg.to_string()));\n"
            "    }\n");
    for (int i = 0; i < m->n_hal; i++)
        sb_printf(&b,
                  "\n    fn %s(&mut self, value: %s) {\n"
                  "        self.probe.borrow_mut().calls.push((\"%s\".to_string(), value as i64));\n"
                  "    }\n",
                  m->hal[i].call, m->hal[i].arg, m->hal[i].call);
    sb_puts(&b, "}\n");
    add(g, "src/gen/fake.rs", &b, 0);
}

static void gen_machine(const Model *m, GenSet *g) {
    SB b;
    sb_init(&b);
    header(&b, m);
    sb_puts(&b,
            "//! Machine wiring: states, events and every (state, event) pair.\n"
            "//! There is deliberately no wildcard arm anywhere in this file.\n\n"
            "use super::hal::{Hal, SafeHal};\n");
    if (m->n_actions) sb_puts(&b, "use crate::actions;\n");
    if (m->n_services) sb_puts(&b, "use crate::services;\n");

    /* State enum */
    sb_puts(&b, "\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum State {\n");
    for (int i = 0; i < m->n_states; i++) sb_printf(&b, "    %s,\n", m->states[i].name);
    sb_printf(&b, "}\n\nimpl State {\n    pub const ALL: [State; %d] = [", m->n_states);
    for (int i = 0; i < m->n_states; i++) sb_printf(&b, "%sState::%s", i ? ", " : "", m->states[i].name);
    sb_puts(&b, "];\n\n    /// The stable node ID from the model.\n    pub fn id(self) -> &'static str {\n        match self {\n");
    for (int i = 0; i < m->n_states; i++)
        sb_printf(&b, "            State::%s => \"%s\",\n", m->states[i].name, m->states[i].id);
    sb_puts(&b, "        }\n    }\n}\n");

    /* Event enum */
    sb_puts(&b, "\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum Event {\n");
    for (int i = 0; i < m->events.n; i++) sb_printf(&b, "    %s,\n", ev(m->events.v[i]));
    sb_printf(&b, "}\n\nimpl Event {\n    pub const ALL: [Event; %d] = [", m->events.n);
    for (int i = 0; i < m->events.n; i++) sb_printf(&b, "%sEvent::%s", i ? ", " : "", ev(m->events.v[i]));
    sb_puts(&b, "];\n\n    pub fn name(self) -> &'static str {\n        match self {\n");
    for (int i = 0; i < m->events.n; i++)
        sb_printf(&b, "            Event::%s => \"%s\",\n", ev(m->events.v[i]), m->events.v[i]);
    sb_puts(&b, "        }\n    }\n\n    pub fn from_name(name: &str) -> Option<Event> {\n        Event::ALL.iter().copied().find(|e| e.name() == name)\n    }\n}\n");

    sb_puts(&b,
            "\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n"
            "pub enum Outcome {\n    Transition { from: State, to: State },\n    Ignored,\n}\n");

    /* Services */
    sb_puts(&b, "\n/// Invoked services owned by the machine.\n#[derive(Default)]\npub struct Services {\n");
    for (int i = 0; i < m->n_services; i++) {
        char *ty = snake_to_camel(m->services[i].id);
        sb_printf(&b, "    pub %s: services::%s::%s,\n", m->services[i].id, m->services[i].id, ty);
        free(ty);
    }
    sb_puts(&b, "}\n");

    /* Machine */
    sb_printf(&b,
              "\npub struct Machine {\n    state: State,\n    entered_ms: u64,\n    pub services: Services,\n}\n\n"
              "impl Machine {\n"
              "    /// Starts in the initial state (%s) and runs its entry actions.\n"
              "    pub fn start<H: Hal>(hal: &mut SafeHal<H>) -> Self {\n"
              "        let mut m = Machine { state: State::%s, entered_ms: hal.now_ms(), services: Services::default() };\n"
              "        m.enter(hal);\n"
              "        m\n"
              "    }\n\n"
              "    /// Places the machine in `state` without running any action. Used by generated tests.\n"
              "    #[doc(hidden)]\n"
              "    pub fn at(state: State, now_ms: u64) -> Self {\n"
              "        Machine { state, entered_ms: now_ms, services: Services::default() }\n"
              "    }\n\n"
              "    pub fn state(&self) -> State {\n        self.state\n    }\n\n"
              "    pub fn entered_ms(&self) -> u64 {\n        self.entered_ms\n    }\n\n",
              initial_name(m), initial_name(m));

    /* send */
    sb_puts(&b,
            "    pub fn send<H: Hal>(&mut self, event: Event, hal: &mut SafeHal<H>) -> Outcome {\n"
            "        let (to, trace) = match (self.state, event) {\n");
    for (int i = 0; i < m->n_states; i++) {
        const State *s = &m->states[i];
        for (int k = 0; k < m->events.n; k++) {
            const char *e = m->events.v[k];
            const char *t = state_target(s, e);
            if (t)
                sb_printf(&b, "            (State::%s, Event::%s) => (State::%s, \"%s --%s--> %s\"),\n", s->name, ev(e),
                          state_name(m, t), s->id, e, t);
            else
                sb_printf(&b, "            (State::%s, Event::%s) => return Outcome::Ignored,\n", s->name, ev(e));
        }
    }
    sb_puts(&b,
            "        };\n"
            "        let from = self.state;\n"
            "        hal.log(trace);\n"
            "        self.exit(hal);\n"
            "        self.state = to;\n"
            "        self.entered_ms = hal.now_ms();\n"
            "        self.enter(hal);\n"
            "        Outcome::Transition { from, to }\n"
            "    }\n\n");

    /* enter / exit */
    for (int pass = 0; pass < 2; pass++) {
        sb_printf(&b, "    fn %s<H: Hal>(&mut self, hal: &mut SafeHal<H>) {\n", pass ? "exit" : "enter");
        int any = 0;
        for (int i = 0; i < m->n_states; i++) {
            const StrList *l = pass ? &m->states[i].exit : &m->states[i].entry;
            if (l->n) any = 1;
        }
        if (!any) sb_puts(&b, "        let _ = hal;\n");
        sb_puts(&b, "        match self.state {\n");
        for (int i = 0; i < m->n_states; i++) {
            const State *s = &m->states[i];
            const StrList *l = pass ? &s->exit : &s->entry;
            if (!l->n) {
                sb_printf(&b, "            State::%s => {}\n", s->name);
                continue;
            }
            sb_printf(&b, "            State::%s => {\n", s->name);
            for (int k = 0; k < l->n; k++) sb_printf(&b, "                actions::%s::run(hal);\n", l->v[k]);
            sb_puts(&b, "            }\n");
        }
        sb_puts(&b, "        }\n    }\n\n");
    }

    /* tick */
    sb_puts(&b,
            "    /// Advances safety watchdogs, `after` timers and invoked services, in that\n"
            "    /// order. Call it regularly (e.g. every 10 ms on the device).\n"
            "    pub fn tick<H: Hal>(&mut self, hal: &mut SafeHal<H>) {\n"
            "        let elapsed = hal.now_ms().saturating_sub(self.entered_ms);\n");
    for (int i = 0; i < m->n_invariants; i++) {
        const Invariant *v = &m->invariants[i];
        if (v->kind != INV_MAX_TIME_IN_STATE) continue;
        sb_printf(&b,
                  "        // @invariant %s: at most %ld ms in %s.\n"
                  "        if self.state == State::%s && elapsed >= %ld {\n"
                  "            self.send(Event::%s, hal);\n"
                  "            return;\n"
                  "        }\n",
                  v->id, v->limit_ms, v->state, state_name(m, v->state), v->limit_ms, ev(v->exit_event));
    }
    sb_puts(&b, "        let timer = match self.state {\n");
    for (int i = 0; i < m->n_states; i++) {
        const State *s = &m->states[i];
        if (s->has_after)
            sb_printf(&b, "            State::%s => (elapsed >= %ld).then_some(Event::%s),\n", s->name, s->after_ms,
                      ev(s->after_event));
        else
            sb_printf(&b, "            State::%s => None,\n", s->name);
    }
    sb_puts(&b,
            "        };\n"
            "        if let Some(event) = timer {\n"
            "            self.send(event, hal);\n"
            "            return;\n"
            "        }\n"
            "        if let Some(event) = self.poll_services(hal) {\n"
            "            self.send(event, hal);\n"
            "        }\n"
            "    }\n\n");

    sb_puts(&b, "    fn poll_services<H: Hal>(&mut self, hal: &mut SafeHal<H>) -> Option<Event> {\n");
    if (!m->n_services) sb_puts(&b, "        let _ = hal;\n");
    sb_puts(&b, "        match self.state {\n");
    for (int i = 0; i < m->n_states; i++) {
        const State *s = &m->states[i];
        if (!s->invoke.n) {
            sb_printf(&b, "            State::%s => None,\n", s->name);
            continue;
        }
        sb_printf(&b, "            State::%s => {\n", s->name);
        for (int k = 0; k < s->invoke.n; k++) {
            const Service *svc = model_service(m, s->invoke.v[k]);
            sb_printf(&b, "                if let Some(e) = self.services.%s.poll(hal) {\n", svc->id);
            if (svc->emits.n) {
                sb_puts(&b, "                    if matches!(e, ");
                for (int x = 0; x < svc->emits.n; x++) sb_printf(&b, "%sEvent::%s", x ? " | " : "", ev(svc->emits.v[x]));
                sb_puts(&b, ") {\n                        return Some(e);\n                    }\n");
            }
            sb_printf(&b, "                    hal.log(\"%s emitted an event it does not declare in 'emits'\");\n", svc->id);
            sb_puts(&b, "                }\n");
        }
        sb_puts(&b, "                None\n            }\n");
    }
    sb_puts(&b, "        }\n    }\n}\n");
    add(g, "src/gen/machine.rs", &b, 0);
}

static void users_of_action(const Model *m, const char *id, SB *b) {
    for (int i = 0; i < m->n_states; i++) {
        if (sl_contains(&m->states[i].entry, id)) sb_printf(b, "// @node %s (entry)\n", m->states[i].id);
        if (sl_contains(&m->states[i].exit, id)) sb_printf(b, "// @node %s (exit)\n", m->states[i].id);
    }
}

static void gen_scaffolds(const Model *m, GenSet *g) {
    for (int i = 0; i < m->n_actions; i++) {
        const Action *a = &m->actions[i];
        SB b;
        sb_init(&b);
        sb_printf(&b, "// @action %s\n", a->id);
        users_of_action(m, a->id, &b);
        sb_printf(&b, "// @stub %s\n", a->note ? a->note : "placeholder written by stategate; replace with real logic");
        sb_printf(&b,
                  "\nuse crate::gen::hal::{Hal, SafeHal};\n\n"
                  "pub fn run<H: Hal>(hal: &mut SafeHal<H>) {\n"
                  "    hal.log(\"%s (stub)\");\n"
                  "}\n",
                  a->id);
        char path[512];
        snprintf(path, sizeof path, "src/actions/%s.rs", a->id);
        add(g, path, &b, 1);
    }
    for (int i = 0; i < m->n_services; i++) {
        const Service *s = &m->services[i];
        SB b;
        sb_init(&b);
        sb_printf(&b, "// @service %s\n", s->id);
        for (int k = 0; k < m->n_states; k++)
            if (sl_contains(&m->states[k].invoke, s->id)) sb_printf(&b, "// @node %s (invoke)\n", m->states[k].id);
        sb_printf(&b, "// @stub %s\n", s->note ? s->note : "placeholder written by stategate; replace with real logic");
        char *ty = snake_to_camel(s->id);
        sb_printf(&b,
                  "\nuse crate::gen::hal::{Hal, SafeHal};\nuse crate::gen::machine::Event;\n\n"
                  "#[derive(Default)]\npub struct %s {}\n\n"
                  "impl %s {\n"
                  "    /// Called on every tick while an invoking state is active.\n"
                  "    pub fn poll<H: Hal>(&mut self, hal: &mut SafeHal<H>) -> Option<Event> {\n"
                  "        let _ = hal;\n"
                  "        None\n"
                  "    }\n"
                  "}\n",
                  ty, ty);
        free(ty);
        char path[512];
        snprintf(path, sizeof path, "src/services/%s.rs", s->id);
        add(g, path, &b, 1);
    }
}

static void test_prelude(SB *b, const Model *m) {
    header(b, m);
    sb_printf(b,
              "// Test names are node and event IDs joined by `__`.\n#![allow(non_snake_case)]\n"
              "\nuse %s::gen::fake::FakeHal;\n"
              "use %s::gen::hal::SafeHal;\n"
              "#[allow(unused_imports)]\n"
              "use %s::gen::machine::{Event, Machine, Outcome, State};\n\n"
              "#[allow(dead_code)]\n"
              "fn hal() -> SafeHal<FakeHal> {\n    SafeHal::new(FakeHal::new().0)\n}\n",
              m->id, m->id, m->id);
}

static void gen_tests(const Model *m, GenSet *g) {
    SB b;
    sb_init(&b);
    test_prelude(&b, m);
    for (int i = 0; i < m->n_states; i++) {
        if (!m->states[i].initial) continue;
        char *sid = id_to_snake(m->states[i].id);
        sb_printf(&b,
                  "\n/// @covers %s (initial)\n#[test]\nfn starts_in__%s() {\n"
                  "    let mut hal = hal();\n    let m = Machine::start(&mut hal);\n    assert_eq!(m.state(), State::%s);\n}\n",
                  m->states[i].id, sid, m->states[i].name);
        free(sid);
    }
    for (int i = 0; i < m->n_states; i++) {
        const State *s = &m->states[i];
        char *sid = id_to_snake(s->id);
        for (int k = 0; k < m->events.n; k++) {
            const char *e = m->events.v[k];
            const char *t = state_target(s, e);
            char *el = xstrdup(e);
            for (char *p = el; *p; p++) if (*p >= 'A' && *p <= 'Z') *p = (char)(*p + 32);
            if (t) {
                char *tid = id_to_snake(t);
                sb_printf(&b,
                          "\n/// @covers %s --%s--> %s\n#[test]\nfn %s__%s__%s() {\n"
                          "    let mut hal = hal();\n    let mut m = Machine::at(State::%s, 0);\n"
                          "    assert_eq!(m.send(Event::%s, &mut hal), Outcome::Transition { from: State::%s, to: State::%s });\n"
                          "    assert_eq!(m.state(), State::%s);\n}\n",
                          s->id, e, t, sid, el, tid, s->name, ev(e), s->name, state_name(m, t), state_name(m, t));
                free(tid);
            } else {
                sb_printf(&b,
                          "\n/// @covers %s ignores %s\n#[test]\nfn %s__%s__ignored() {\n"
                          "    let mut hal = hal();\n    let mut m = Machine::at(State::%s, 0);\n"
                          "    assert_eq!(m.send(Event::%s, &mut hal), Outcome::Ignored);\n"
                          "    assert_eq!(m.state(), State::%s);\n}\n",
                          s->id, e, sid, el, s->name, ev(e), s->name);
            }
            free(el);
        }
        free(sid);
    }
    add(g, "tests/transitions.rs", &b, 0);

    sb_init(&b);
    test_prelude(&b, m);
    for (int i = 0; i < m->n_invariants; i++) {
        const Invariant *v = &m->invariants[i];
        char *vid = id_to_snake(v->id);
        if (v->kind == INV_EVERY_STATE_HANDLES) {
            for (int s = 0; s < m->n_states; s++) {
                char *sid = id_to_snake(m->states[s].id);
                sb_printf(&b,
                          "\n/// @covers %s in %s: %s --> %s\n#[test]\nfn %s__%s() {\n"
                          "    let mut hal = hal();\n    let mut m = Machine::at(State::%s, 0);\n"
                          "    m.send(Event::%s, &mut hal);\n    assert_eq!(m.state(), State::%s);\n}\n",
                          v->id, m->states[s].id, v->event, v->target, vid, sid, m->states[s].name, ev(v->event),
                          state_name(m, v->target));
                free(sid);
            }
        } else if (v->kind == INV_MAX_TIME_IN_STATE) {
            char *sid = id_to_snake(v->state);
            sb_printf(&b,
                      "\n/// @covers %s: %s lasts at most %ld ms\n#[test]\nfn %s__%s_exits_by_%ld_ms() {\n"
                      "    let (fake, probe) = FakeHal::new();\n    let mut hal = SafeHal::new(fake);\n"
                      "    let mut m = Machine::at(State::%s, 0);\n"
                      "    probe.borrow_mut().now_ms = %ld;\n    m.tick(&mut hal);\n"
                      "    assert_ne!(m.state(), State::%s);\n}\n",
                      v->id, v->state, v->limit_ms, vid, sid, v->limit_ms, state_name(m, v->state), v->limit_ms,
                      state_name(m, v->state));
            free(sid);
        } else if (v->kind == INV_HAL_CLAMP) {
            const HalCall *h = model_hal(m, v->call);
            sb_printf(&b,
                      "\n/// @covers %s: %s is clamped to %ld\n#[test]\nfn %s__%s_clamped_to_%ld() {\n"
                      "    let (fake, probe) = FakeHal::new();\n    let mut hal = SafeHal::new(fake);\n"
                      "    hal.%s(%s);\n"
                      "    assert_eq!(probe.borrow().last(\"%s\"), Some(%ld));\n}\n",
                      v->id, v->call, v->max, vid, v->call, v->max, v->call, rust_max(h ? h->arg : "u8"), v->call, v->max);
        }
        free(vid);
    }
    add(g, "tests/invariants.rs", &b, 0);
}

static void gen_sim(const Model *m, GenSet *g) {
    SB b;
    sb_init(&b);
    header(&b, m);
    sb_printf(&b,
              "//! Runs the machine on fake hardware and prints every log line.\n"
              "//! Usage: cargo run --example sim -- <run_ms> [EVENT ...]\n"
              "//! The listed events are sent at t = 0, in order.\n\n"
              "use %s::gen::fake::FakeHal;\nuse %s::gen::hal::SafeHal;\nuse %s::gen::machine::{Event, Machine};\n\n"
              "fn main() {\n"
              "    let args: Vec<String> = std::env::args().skip(1).collect();\n"
              "    let run_ms: u64 = args.first().and_then(|a| a.parse().ok()).unwrap_or(15_000);\n"
              "    let (fake, probe) = FakeHal::new();\n"
              "    let mut hal = SafeHal::new(fake);\n"
              "    let mut m = Machine::start(&mut hal);\n"
              "    for name in args.iter().skip(1) {\n"
              "        match Event::from_name(name) {\n"
              "            Some(e) => {\n                m.send(e, &mut hal);\n            }\n"
              "            None => eprintln!(\"unknown event {name}\"),\n"
              "        }\n"
              "    }\n"
              "    let mut printed = 0;\n"
              "    let mut t = 0;\n"
              "    while t <= run_ms {\n"
              "        probe.borrow_mut().now_ms = t;\n"
              "        m.tick(&mut hal);\n"
              "        let p = probe.borrow();\n"
              "        for (at, line) in p.logs.iter().skip(printed) {\n"
              "            println!(\"{:>7.1}s  {line}\", *at as f64 / 1000.0);\n"
              "        }\n"
              "        printed = p.logs.len();\n"
              "        t += 10;\n"
              "    }\n"
              "    println!(\"final state: {}\", m.state().id());\n"
              "}\n",
              m->id, m->id, m->id);
    add(g, "examples/sim.rs", &b, 0);
}

void gen_rust(const Model *m, GenSet *out) {
    memset(out, 0, sizeof *out);
    gen_cargo(m, out);
    gen_lib(m, out);
    gen_hal(m, out);
    gen_fake(m, out);
    gen_machine(m, out);
    gen_tests(m, out);
    gen_sim(m, out);
    gen_scaffolds(m, out);
}
