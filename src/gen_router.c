/* The system router for C: queues, the per-machine HAL that routes sends,
 * and a step function per machine. Generated at the system root. */
#include "gen_router.h"

#include <ctype.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static void add(GenSet *g, const char *path, SB *content) {
    if (g->n == g->cap) {
        g->cap = g->cap ? g->cap * 2 : 16;
        g->v = xrealloc(g->v, sizeof(GenFile) * (size_t)g->cap);
    }
    g->v[g->n].path = xstrdup(path);
    g->v[g->n].content = content->s;
    g->v[g->n].scaffold = 0;
    g->n++;
}

static char *ring_put(char *s) {
    static char *ring[16];
    static int i;
    i = (i + 1) % 16;
    free(ring[i]);
    ring[i] = s;
    return s;
}

static const char *up(const char *s) {
    char *u = xstrdup(s);
    for (char *p = u; *p; p++) *p = (char)toupper((unsigned char)*p);
    return ring_put(u);
}

static const char *lo(const char *s) {
    char *u = xstrdup(s);
    for (char *p = u; *p; p++) *p = (char)tolower((unsigned char)*p);
    return ring_put(u);
}

static const char *ctype(const char *arg) {
    if (!strcmp(arg, "u8")) return "uint8_t";
    if (!strcmp(arg, "u16")) return "uint16_t";
    if (!strcmp(arg, "u32")) return "uint32_t";
    if (!strcmp(arg, "bool")) return "bool";
    return "int32_t";
}

static void header(SB *b, const char *comment) {
    sb_printf(b, "%s @generated by stategate from system.yaml. Do not edit: change the system and run `stategate gen`.%s\n",
              comment, !strcmp(comment, "/*") ? " */" : "");
}

static const char *drop_enum(const char *drop) {
    if (drop && !strcmp(drop, "oldest")) return "SG_DROP_OLDEST";
    if (drop && !strcmp(drop, "newest")) return "SG_DROP_NEWEST";
    return "SG_DROP_NEVER";
}

static int is_queue(const Channel *c) { return !strcmp(c->kind, "queue"); }

static void gen_queue(GenSet *g) {
    SB b;
    sb_init(&b);
    header(&b, "/*");
    sb_puts(&b,
            "/* A fixed-size queue of fixed-size items. FreeRTOS queues on ESP-IDF, a ring\n"
            " * buffer everywhere else (one thread: the host tests and simulator). */\n"
            "#ifndef SG_QUEUE_H\n#define SG_QUEUE_H\n\n"
            "#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n\n"
            "/* What a full queue does with one more item. never: the sender waits for room\n"
            " * (on the host, where nothing would make room, the item is dropped and\n"
            " * counted); oldest: the oldest item is dropped; newest: the new item is. */\n"
            "typedef enum { SG_DROP_NEVER, SG_DROP_OLDEST, SG_DROP_NEWEST } sg_drop_t;\n\n"
            "#ifdef ESP_PLATFORM\n"
            "#include \"freertos/FreeRTOS.h\"\n#include \"freertos/queue.h\"\n"
            "typedef struct {\n"
            "    QueueHandle_t q;\n    StaticQueue_t qs;\n    uint8_t *scratch;\n"
            "    size_t elem;\n    sg_drop_t drop;\n    uint32_t dropped;\n"
            "} sg_queue_t;\n"
            "#else\n"
            "typedef struct {\n"
            "    uint8_t *buf;\n    size_t elem, depth, head, count;\n"
            "    sg_drop_t drop;\n    uint32_t dropped;\n"
            "} sg_queue_t;\n"
            "#endif\n\n"
            "/* storage holds depth + 1 items (the extra one is scratch space). */\n"
            "void sg_queue_init(sg_queue_t *q, void *storage, size_t elem, size_t depth, sg_drop_t drop);\n"
            "/* True when the new item is in the queue. */\n"
            "bool sg_queue_push(sg_queue_t *q, const void *item);\n"
            "bool sg_queue_pop(sg_queue_t *q, void *item);\n"
            "size_t sg_queue_count(const sg_queue_t *q);\n\n#endif\n");
    add(g, "router/sg_queue.h", &b);

    sb_init(&b);
    header(&b, "/*");
    sb_puts(&b,
            "#include \"sg_queue.h\"\n\n#include <string.h>\n\n"
            "#ifdef ESP_PLATFORM\n\n"
            "void sg_queue_init(sg_queue_t *q, void *storage, size_t elem, size_t depth, sg_drop_t drop) {\n"
            "    q->q = xQueueCreateStatic((UBaseType_t)depth, (UBaseType_t)elem, storage, &q->qs);\n"
            "    q->scratch = (uint8_t *)storage + depth * elem;\n"
            "    q->elem = elem;\n    q->drop = drop;\n    q->dropped = 0;\n"
            "}\n\n"
            "bool sg_queue_push(sg_queue_t *q, const void *item) {\n"
            "    switch (q->drop) {\n"
            "    case SG_DROP_NEVER:\n"
            "        return xQueueSend(q->q, item, portMAX_DELAY) == pdTRUE;\n"
            "    case SG_DROP_NEWEST:\n"
            "        if (xQueueSend(q->q, item, 0) == pdTRUE) return true;\n"
            "        q->dropped++;\n"
            "        return false;\n"
            "    case SG_DROP_OLDEST:\n"
            "        while (xQueueSend(q->q, item, 0) != pdTRUE)\n"
            "            if (xQueueReceive(q->q, q->scratch, 0) == pdTRUE) q->dropped++;\n"
            "        return true;\n"
            "    }\n"
            "    return false;\n"
            "}\n\n"
            "bool sg_queue_pop(sg_queue_t *q, void *item) {\n    return xQueueReceive(q->q, item, 0) == pdTRUE;\n}\n\n"
            "size_t sg_queue_count(const sg_queue_t *q) {\n    return (size_t)uxQueueMessagesWaiting(q->q);\n}\n\n"
            "#else\n\n"
            "void sg_queue_init(sg_queue_t *q, void *storage, size_t elem, size_t depth, sg_drop_t drop) {\n"
            "    q->buf = storage;\n    q->elem = elem;\n    q->depth = depth;\n    q->head = 0;\n    q->count = 0;\n"
            "    q->drop = drop;\n    q->dropped = 0;\n"
            "}\n\n"
            "bool sg_queue_push(sg_queue_t *q, const void *item) {\n"
            "    if (q->count == q->depth) {\n"
            "        q->dropped++;\n"
            "        switch (q->drop) {\n"
            "        case SG_DROP_NEVER:\n"
            "        case SG_DROP_NEWEST:\n"
            "            return false;\n"
            "        case SG_DROP_OLDEST:\n"
            "            q->head = (q->head + 1) % q->depth;\n"
            "            q->count--;\n"
            "            break;\n"
            "        }\n"
            "    }\n"
            "    memcpy(q->buf + ((q->head + q->count) % q->depth) * q->elem, item, q->elem);\n"
            "    q->count++;\n"
            "    return true;\n"
            "}\n\n"
            "bool sg_queue_pop(sg_queue_t *q, void *item) {\n"
            "    if (!q->count) return false;\n"
            "    memcpy(item, q->buf + q->head * q->elem, q->elem);\n"
            "    q->head = (q->head + 1) % q->depth;\n"
            "    q->count--;\n"
            "    return true;\n"
            "}\n\n"
            "size_t sg_queue_count(const sg_queue_t *q) {\n    return q->count;\n}\n\n"
            "#endif\n");
    add(g, "router/sg_queue.c", &b);
}

static void gen_router_h(const SgSystem *s, GenSet *g) {
    const char *S = s->id;
    long pmax = 1;
    for (int i = 0; i < s->n_channels; i++)
        if (s->channels[i].payload > pmax) pmax = s->channels[i].payload;
    SB b;
    sb_init(&b);
    header(&b, "/*");
    sb_printf(&b,
              "/* The %s system: every machine, its HAL routed through the channels in\n"
              " * system.yaml, and one step function per machine.\n"
              " *\n"
              " * On a device, give each machine its own task (or share one) and call its\n"
              " * step function regularly, e.g. every 10 ms. A step handles every event\n"
              " * queued for the machine, in channel order, then ticks it. A sync channel\n"
              " * delivers at once, inside the sender's call, on the sender's task. An event\n"
              " * for a machine with several instances goes to every instance. */\n"
              "#ifndef %s_ROUTER_H\n#define %s_ROUTER_H\n\n#include \"sg_queue.h\"\n\n",
              S, up(S), up(S));
    for (int i = 0; i < s->n_machines; i++)
        sb_printf(&b, "#include \"../%s/src/gen/hal.h\"\n#include \"../%s/src/gen/machine.h\"\n#include \"../%s/src/gen/trace.h\"\n",
                  s->machines[i].dir, s->machines[i].dir, s->machines[i].dir);
    sb_printf(&b,
              "\n/* The largest payload any channel carries, in bytes. */\n#define %s_PAYLOAD_MAX %ld\n\n"
              "typedef struct {\n    int event;\n    uint16_t len;\n    uint8_t data[%s_PAYLOAD_MAX];\n} %s_msg_t;\n\n",
              up(S), pmax, up(S), S);
    for (int i = 0; i < s->n_machines; i++)
        sb_printf(&b, "#define %s_%s_INSTANCES %d\n", up(S), up(s->machines[i].id), s->machines[i].instances);
    sb_printf(&b, "\n#define %s_CHANNEL_COUNT %d\n", up(S), s->n_channels);
    for (int i = 0; i < s->n_channels; i++) {
        const Channel *c = &s->channels[i];
        sb_printf(&b, "#define %s_CH_%s_%s_%s %d /* %s */\n", up(S), up(c->from), up(c->to), c->event, i,
                  is_queue(c) ? "queue" : "sync");
    }
    sb_printf(&b,
              "\nstruct %s_system;\n\ntypedef struct {\n    struct %s_system *sys;\n    int instance;\n"
              "    const void *payload;\n    size_t payload_len;\n} %s_slot_t;\n\n",
              S, S, S);
    sb_printf(&b, "/* Each machine's board HAL, shared by its instances. Their payload, send,\n * instance, param and trace fields are not used: the router supplies them. */\ntypedef struct {\n");
    for (int i = 0; i < s->n_machines; i++) sb_printf(&b, "    %s_hal_t %s;\n", s->machines[i].id, s->machines[i].id);
    sb_printf(&b, "} %s_boards_t;\n\ntypedef struct %s_system {\n    %s_boards_t boards;\n", S, S, S);
    for (int i = 0; i < s->n_machines; i++) {
        const char *m = s->machines[i].id;
        int n = s->machines[i].instances;
        sb_printf(&b, "    %s_machine_t %s[%d];\n    %s_safe_hal_t %s_hal[%d];\n    %s_slot_t %s_slot[%d];\n", m, m, n, m, m, n, S, m, n);
    }
    sb_printf(&b, "    sg_queue_t queue[%s_CHANNEL_COUNT]; /* sync channels leave theirs unused */\n", up(S));
    sb_puts(&b, "    void (*trace)(void *ctx, const uint8_t *record, size_t len);\n    void *trace_ctx;\n    uint16_t trace_seq;\n");
    for (int i = 0; i < s->n_channels; i++)
        if (is_queue(&s->channels[i])) sb_printf(&b, "    %s_msg_t storage_%d[%ld];\n", S, i, s->channels[i].depth + 1);
    sb_printf(&b, "} %s_system_t;\n\n", S);
    sb_printf(&b,
              "/* Wires every machine to its board and the channels, then starts each one in\n"
              " * the order system.yaml lists them. */\n"
              "void %s_init(%s_system_t *s, const %s_boards_t *boards);\n",
              S, S, S);
    for (int i = 0; i < s->n_machines; i++) {
        const char *m = s->machines[i].id;
        sb_printf(&b,
                  "/* Delivers an event to %s now (every instance), on the caller's task: for\n"
                  " * events from outside the system, called from %s's own task. */\n"
                  "void %s_post_%s(%s_system_t *s, %s_event_t event, const void *data, size_t len);\n",
                  m, m, S, m, S, m);
        if (s->machines[i].instances > 1)
            sb_printf(&b, "/* Delivers an event to one instance of %s. */\nvoid %s_post_%s_at(%s_system_t *s, int instance, %s_event_t event, const void *data, size_t len);\n",
                      m, S, m, S, m);
        sb_printf(&b, "void %s_step_%s(%s_system_t *s);\n", S, m, S);
    }
    sb_printf(&b,
              "/* Steps every machine once, in order. For one task, the host tests and the simulator. */\n"
              "void %s_step_all(%s_system_t *s);\n"
              "/* Events a full queue dropped (oldest or newest), or could not take (never). */\n"
              "uint32_t %s_dropped(const %s_system_t *s, int channel);\n"
              "size_t %s_queued(const %s_system_t *s, int channel);\n\n",
              S, S, S, S, S, S);
    int hsize = 5;
    for (int i = 0; i < s->n_machines; i++) hsize += 1 + (int)strlen(s->machines[i].id) + 32;
    sb_printf(&b,
              "/* A transition log of the whole system (see trace.h in any machine). Write\n"
              " * the header once, then pass a sink to %s_set_trace: it gets one record per\n"
              " * transition, machine numbered in system.yaml order, from whichever task made\n"
              " * it, so a sink shared by several tasks must lock. NULL turns tracing off. */\n"
              "#define %s_TRACE_HEADER_SIZE %d\n"
              "size_t %s_trace_header(uint8_t out[%s_TRACE_HEADER_SIZE]);\n"
              "void %s_set_trace(%s_system_t *s, void (*sink)(void *ctx, const uint8_t *record, size_t len), void *ctx);\n\n#endif\n",
              S, up(S), hsize, S, up(S), S, S);
    char path[256];
    snprintf(path, sizeof path, "router/%s.h", S);
    add(g, path, &b);
}

static void gen_router_c(const SgSystem *s, GenSet *g) {
    const char *S = s->id;
    SB b;
    sb_init(&b);
    header(&b, "/*");
    sb_printf(&b, "#include \"%s.h\"\n\n#include <stdio.h>\n#include <string.h>\n", S);

    for (int i = 0; i < s->n_machines; i++) {
        const SysMachine *sm = &s->machines[i];
        const SgModel *mm = &sm->model;
        const char *m = sm->id;
        sb_printf(&b,
                  "\n/* ---- %s: its board HAL behind the router ---- */\n\n"
                  "static uint64_t rt_%s_now_ms(void *ctx) {\n"
                  "    %s_slot_t *sl = ctx;\n    return sl->sys->boards.%s.now_ms(sl->sys->boards.%s.ctx);\n}\n\n",
                  m, m, S, m, m);
        if (sm->instances > 1)
            sb_printf(&b,
                      "/* Log lines from an instance start with its number. */\n"
                      "static void rt_%s_log(void *ctx, const char *msg) {\n"
                      "    %s_slot_t *sl = ctx;\n    char line[192];\n"
                      "    snprintf(line, sizeof line, \"[%%d] %%s\", sl->instance, msg);\n"
                      "    sl->sys->boards.%s.log(sl->sys->boards.%s.ctx, line);\n}\n\n",
                      m, S, m, m);
        else
            sb_printf(&b,
                      "static void rt_%s_log(void *ctx, const char *msg) {\n"
                      "    %s_slot_t *sl = ctx;\n    sl->sys->boards.%s.log(sl->sys->boards.%s.ctx, msg);\n}\n\n",
                      m, S, m, m);
        sb_printf(&b,
                  "static void rt_%s_trace(void *ctx, uint8_t from, uint8_t event, uint8_t to) {\n"
                  "    %s_slot_t *sl = ctx;\n    %s_system_t *s = sl->sys;\n    if (!s->trace) return;\n"
                  "    uint8_t rec[SG_TRACE_RECORD_SIZE];\n"
                  "    sg_trace_record(rec, (uint32_t)s->boards.%s.now_ms(s->boards.%s.ctx), s->trace_seq++, %d, (uint8_t)sl->instance, from, event, to);\n"
                  "    s->trace(s->trace_ctx, rec, sizeof rec);\n}\n\n"
                  "static const void *rt_%s_payload(void *ctx, size_t *len) {\n"
                  "    %s_slot_t *sl = ctx;\n    *len = sl->payload_len;\n    return sl->payload;\n}\n\n"
                  "static int rt_%s_instance(void *ctx) {\n    return ((%s_slot_t *)ctx)->instance;\n}\n",
                  m, S, S, m, m, i, m, S, m, S);
        if (mm->params.n) {
            sb_printf(&b, "\n/* [instance][param], in the order of %s's model. */\nstatic const int32_t %s_params[%d][%d] = {\n", m, m,
                      sm->instances, mm->params.n);
            for (int k = 0; k < sm->instances; k++) {
                sb_puts(&b, "    {");
                for (int q = 0; q < mm->params.n; q++) {
                    long v = 0;
                    for (int x = 0; x < sm->param_names.n; x++)
                        if (!strcmp(sm->param_names.v[x], mm->params.v[q])) v = sm->param_values[k * sm->param_names.n + x];
                    sb_printf(&b, "%s%ld", q ? ", " : "", v);
                }
                sb_puts(&b, "},\n");
            }
            sb_printf(&b, "};\n\nstatic int32_t rt_%s_param(void *ctx, int index) {\n    return %s_params[((%s_slot_t *)ctx)->instance][index];\n}\n",
                      m, m, S);
        }
        for (int k = 0; k < mm->n_hal; k++)
            sb_printf(&b,
                      "\nstatic void rt_%s_%s(void *ctx, %s value) {\n"
                      "    %s_slot_t *sl = ctx;\n    sl->sys->boards.%s.%s(sl->sys->boards.%s.ctx, value);\n}\n",
                      m, mm->hal[k].call, ctype(mm->hal[k].arg), S, m, mm->hal[k].call, m);
    }

    /* push: one queue channel */
    sb_printf(&b,
              "\n/* ---- delivery ---- */\n\n"
              "static void push(%s_system_t *s, int ch, int event, const void *data, size_t len, void (*log)(void *, const char *),\n"
              "                 void *log_ctx) {\n"
              "    %s_msg_t msg;\n"
              "    char line[96];\n"
              "    if (len > %s_PAYLOAD_MAX) {\n"
              "        snprintf(line, sizeof line, \"channel %%d: payload of %%u bytes is over the %%d-byte limit, dropped\", ch,\n"
              "                 (unsigned)len, %s_PAYLOAD_MAX);\n"
              "        log(log_ctx, line);\n"
              "        return;\n"
              "    }\n"
              "    memset(&msg, 0, sizeof msg);\n"
              "    msg.event = event;\n"
              "    msg.len = (uint16_t)len;\n"
              "    if (len) memcpy(msg.data, data, len);\n"
              "    if (!sg_queue_push(&s->queue[ch], &msg)) {\n"
              "        snprintf(line, sizeof line, \"channel %%d is full: event dropped\", ch);\n"
              "        log(log_ctx, line);\n"
              "    }\n"
              "}\n",
              S, S, up(S), up(S));

    for (int i = 0; i < s->n_machines; i++) {
        const char *m = s->machines[i].id;
        sb_printf(&b,
                  "\n%svoid %s_post_%s_at(%s_system_t *s, int instance, %s_event_t event, const void *data, size_t len) {\n"
                  "    %s_slot_t *sl = &s->%s_slot[instance];\n"
                  "    const void *was = sl->payload;\n    size_t was_len = sl->payload_len;\n"
                  "    sl->payload = data;\n    sl->payload_len = len;\n"
                  "    %s_send(&s->%s[instance], event, &s->%s_hal[instance]);\n"
                  "    sl->payload = was;\n    sl->payload_len = was_len;\n"
                  "}\n\n"
                  "void %s_post_%s(%s_system_t *s, %s_event_t event, const void *data, size_t len) {\n"
                  "    for (int i = 0; i < %d; i++) %s_post_%s_at(s, i, event, data, len);\n"
                  "}\n",
                  s->machines[i].instances > 1 ? "" : "static ", S, m, S, m, S, m, m, m, m, S, m, S, m,
                  s->machines[i].instances, S, m);
    }

    for (int i = 0; i < s->n_machines; i++) {
        const SysMachine *sm = &s->machines[i];
        const char *m = sm->id;
        if (!sm->model.sends.n) continue;
        sb_printf(&b,
                  "\nstatic void rt_%s_send(void *ctx, %s_out_t event, const void *data, size_t len) {\n"
                  "    %s_slot_t *sl = ctx;\n    %s_system_t *s = sl->sys;\n    switch (event) {\n",
                  m, m, S, S);
        for (int k = 0; k < sm->model.sends.n; k++) {
            const char *ev = sm->model.sends.v[k];
            sb_printf(&b, "    case %s_OUT_%s:\n", up(m), ev);
            for (int c = 0; c < s->n_channels; c++) {
                const Channel *ch = &s->channels[c];
                if (strcmp(ch->from, m) || strcmp(ch->event, ev)) continue;
                if (is_queue(ch))
                    sb_printf(&b, "        push(s, %d, %s_EV_%s, data, len, rt_%s_log, ctx);\n", c, up(ch->to), ev, m);
                else
                    sb_printf(&b, "        %s_post_%s(s, %s_EV_%s, data, len);\n", S, ch->to, up(ch->to), ev);
            }
            sb_puts(&b, "        break;\n");
        }
        sb_puts(&b, "    }\n}\n");
    }

    /* init */
    sb_printf(&b, "\nvoid %s_init(%s_system_t *s, const %s_boards_t *boards) {\n    memset(s, 0, sizeof *s);\n    s->boards = *boards;\n", S, S, S);
    for (int i = 0; i < s->n_machines; i++) {
        const SysMachine *sm = &s->machines[i];
        const char *m = sm->id;
        sb_printf(&b,
                  "    for (int i = 0; i < %d; i++) {\n"
                  "        %s_hal_t h;\n        memset(&h, 0, sizeof h);\n"
                  "        s->%s_slot[i].sys = s;\n        s->%s_slot[i].instance = i;\n        h.ctx = &s->%s_slot[i];\n"
                  "        h.now_ms = rt_%s_now_ms;\n        h.log = rt_%s_log;\n        h.payload = rt_%s_payload;\n"
                  "        h.instance = rt_%s_instance;\n        h.trace = rt_%s_trace;\n",
                  sm->instances, m, m, m, m, m, m, m, m, m);
        if (sm->model.params.n) sb_printf(&b, "        h.param = rt_%s_param;\n", m);
        for (int k = 0; k < sm->model.n_hal; k++) sb_printf(&b, "        h.%s = rt_%s_%s;\n", sm->model.hal[k].call, m, sm->model.hal[k].call);
        if (sm->model.sends.n) sb_printf(&b, "        h.send = rt_%s_send;\n", m);
        sb_printf(&b, "        s->%s_hal[i] = %s_safe_hal(h);\n    }\n", m, m);
    }
    for (int i = 0; i < s->n_channels; i++) {
        const Channel *c = &s->channels[i];
        if (!is_queue(c)) continue;
        sb_printf(&b, "    sg_queue_init(&s->queue[%d], s->storage_%d, sizeof(%s_msg_t), %ld, %s); /* %s -> %s %s */\n", i, i, S,
                  c->depth, drop_enum(c->drop), c->from, c->to, c->event);
    }
    for (int i = 0; i < s->n_machines; i++)
        sb_printf(&b, "    for (int i = 0; i < %d; i++) %s_start(&s->%s[i], &s->%s_hal[i]);\n", s->machines[i].instances, s->machines[i].id,
                  s->machines[i].id, s->machines[i].id);
    sb_puts(&b, "}\n");

    for (int i = 0; i < s->n_machines; i++) {
        const char *m = s->machines[i].id;
        sb_printf(&b, "\nvoid %s_step_%s(%s_system_t *s) {\n", S, m, S);
        int any = 0;
        for (int c = 0; c < s->n_channels; c++) {
            const Channel *ch = &s->channels[c];
            if (strcmp(ch->to, m) || !is_queue(ch)) continue;
            if (!any) sb_printf(&b, "    %s_msg_t msg;\n", S);
            any = 1;
            sb_printf(&b, "    while (sg_queue_pop(&s->queue[%d], &msg)) /* from %s: %s */\n        %s_post_%s(s, (%s_event_t)msg.event, msg.data, msg.len);\n",
                      c, ch->from, ch->event, S, m, m);
        }
        sb_printf(&b, "    for (int i = 0; i < %d; i++) %s_tick(&s->%s[i], &s->%s_hal[i]);\n}\n", s->machines[i].instances, m, m, m);
    }
    sb_printf(&b, "\nvoid %s_step_all(%s_system_t *s) {\n", S, S);
    for (int i = 0; i < s->n_machines; i++) sb_printf(&b, "    %s_step_%s(s);\n", S, s->machines[i].id);
    sb_printf(&b,
              "}\n\n"
              "uint32_t %s_dropped(const %s_system_t *s, int channel) {\n    return s->queue[channel].dropped;\n}\n\n"
              "size_t %s_queued(const %s_system_t *s, int channel) {\n"
              "    return sg_queue_count(&s->queue[channel]);\n}\n",
              S, S, S, S);
    sb_printf(&b, "\nsize_t %s_trace_header(uint8_t out[%s_TRACE_HEADER_SIZE]) {\n    memcpy(out, \"SGT1\", 4);\n    out[4] = %d;\n    size_t n = 5;\n",
              S, up(S), s->n_machines);
    for (int i = 0; i < s->n_machines; i++) sb_printf(&b, "    n += %s_trace_header_entry(out + n);\n", s->machines[i].id);
    sb_printf(&b,
              "    return n;\n}\n\n"
              "void %s_set_trace(%s_system_t *s, void (*sink)(void *ctx, const uint8_t *record, size_t len), void *ctx) {\n"
              "    s->trace_ctx = ctx;\n    s->trace = sink;\n}\n",
              S, S);
    char path[256];
    snprintf(path, sizeof path, "router/%s.c", S);
    add(g, path, &b);
}

static void gen_router_test(const SgSystem *s, GenSet *g) {
    const char *S = s->id;
    SB b;
    sb_init(&b);
    header(&b, "/*");
    sb_printf(&b,
              "/* Every queue channel holds its depth and then follows its drop policy; every\n"
              " * instance sees its own number and params; the trace names every machine. */\n#include \"unity.h\"\n\n#include \"%s.h\"\n",
              S);
    for (int i = 0; i < s->n_machines; i++) sb_printf(&b, "#include \"../%s/src/gen/fake.h\"\n", s->machines[i].dir);
    sb_puts(&b, "\n");
    for (int i = 0; i < s->n_machines; i++) sb_printf(&b, "static %s_probe_t %s_probe;\n", s->machines[i].id, s->machines[i].id);
    sb_printf(&b, "static %s_system_t sys;\n\nvoid setUp(void) {\n    %s_boards_t boards;\n", S, S);
    for (int i = 0; i < s->n_machines; i++)
        sb_printf(&b, "    boards.%s = %s_fake_hal(&%s_probe);\n", s->machines[i].id, s->machines[i].id, s->machines[i].id);
    sb_printf(&b, "    %s_init(&sys, &boards);\n}\n\nvoid tearDown(void) {}\n", S);
    StrList names = {0};
    for (int c = 0; c < s->n_channels; c++) {
        const Channel *ch = &s->channels[c];
        if (!is_queue(ch)) continue;
        char name[256];
        snprintf(name, sizeof name, "%s_%s_to_%s__holds_%ld_then_drops_%s", lo(ch->event), ch->from, ch->to, ch->depth,
                 ch->drop ? ch->drop : "never");
        sl_push(&names, name);
        sb_printf(&b,
                  "\nstatic void %s(void) {\n"
                  "    for (int i = 0; i < %ld; i++) %s_send_%s(&sys.%s_hal[0], NULL, 0);\n"
                  "    TEST_ASSERT_EQUAL_UINT(%ld, %s_queued(&sys, %d));\n"
                  "    TEST_ASSERT_EQUAL_UINT32(0, %s_dropped(&sys, %d));\n"
                  "    %s_send_%s(&sys.%s_hal[0], NULL, 0);\n"
                  "    TEST_ASSERT_EQUAL_UINT(%ld, %s_queued(&sys, %d));\n"
                  "    TEST_ASSERT_EQUAL_UINT32(1, %s_dropped(&sys, %d));\n"
                  "    %s_step_%s(&sys);\n"
                  "    TEST_ASSERT_EQUAL_UINT(0, %s_queued(&sys, %d));\n"
                  "}\n",
                  name, ch->depth, ch->from, lo(ch->event), ch->from, ch->depth, S, c, S, c, ch->from, lo(ch->event), ch->from,
                  ch->depth, S, c, S, c, S, ch->to, S, c);
    }
    for (int i = 0; i < s->n_machines; i++) {
        const SysMachine *sm = &s->machines[i];
        if (sm->instances < 2 && !sm->model.params.n) continue;
        char name[256];
        snprintf(name, sizeof name, "%s__instances_see_their_number_and_params", sm->id);
        sl_push(&names, name);
        sb_printf(&b, "\nstatic void %s(void) {\n", name);
        for (int k = 0; k < sm->instances; k++) {
            sb_printf(&b, "    TEST_ASSERT_EQUAL_INT(%d, %s_hal_instance(&sys.%s_hal[%d]));\n", k, sm->id, sm->id, k);
            for (int q = 0; q < sm->model.params.n; q++) {
                long v = 0;
                for (int x = 0; x < sm->param_names.n; x++)
                    if (!strcmp(sm->param_names.v[x], sm->model.params.v[q])) v = sm->param_values[k * sm->param_names.n + x];
                sb_printf(&b, "    TEST_ASSERT_EQUAL_INT32(%ld, %s_hal_param_%s(&sys.%s_hal[%d]));\n", v, sm->id, sm->model.params.v[q], sm->id, k);
            }
        }
        sb_puts(&b, "}\n");
    }
    /* The trace: a header naming every machine, then the first transition of the
     * first machine whose initial state has one. */
    sl_push(&names, "trace__header_names_every_machine_and_records_carry_names");
    sb_printf(&b,
              "\nstatic uint8_t trace_buf[64][SG_TRACE_RECORD_SIZE];\nstatic int trace_n;\n\n"
              "static void trace_sink(void *ctx, const uint8_t *record, size_t len) {\n"
              "    (void)ctx;\n    if (trace_n < 64 && len == SG_TRACE_RECORD_SIZE) memcpy(trace_buf[trace_n++], record, len);\n}\n\n"
              "static void trace__header_names_every_machine_and_records_carry_names(void) {\n"
              "    uint8_t h[%s_TRACE_HEADER_SIZE];\n"
              "    TEST_ASSERT_EQUAL_UINT(%s_TRACE_HEADER_SIZE, %s_trace_header(h));\n"
              "    TEST_ASSERT_EQUAL_MEMORY(\"SGT1\", h, 4);\n"
              "    TEST_ASSERT_EQUAL_UINT8(%d, h[4]);\n"
              "    trace_n = 0;\n    %s_set_trace(&sys, trace_sink, NULL);\n",
              up(S), up(S), S, s->n_machines, S);
    int done = 0;
    for (int i = 0; i < s->n_machines && !done; i++) {
        const SgModel *mm = &s->machines[i].model;
        for (int k = 0; k < mm->n_states && !done; k++) {
            const State *st = &mm->states[k];
            if (!st->initial || !st->n_on) continue;
            int ev = model_event_index(mm, st->on[0].event), to = -1;
            for (int q = 0; q < mm->n_states; q++)
                if (!strcmp(mm->states[q].id, st->on[0].target)) to = q;
            if (ev < 0 || to < 0) continue;
            sb_printf(&b,
                      "    %s_post_%s(&sys, (%s_event_t)%d, NULL, 0); /* %s --%s--> %s */\n"
                      "    TEST_ASSERT_TRUE(trace_n >= 1);\n"
                      "    TEST_ASSERT_EQUAL_UINT8(%d, trace_buf[0][6]); /* machine: %s */\n"
                      "    TEST_ASSERT_EQUAL_UINT8(0, trace_buf[0][7]);\n"
                      "    TEST_ASSERT_EQUAL_UINT8(%d, trace_buf[0][8]);\n"
                      "    TEST_ASSERT_EQUAL_UINT8(%d, trace_buf[0][9]);\n"
                      "    TEST_ASSERT_EQUAL_UINT8(%d, trace_buf[0][10]);\n",
                      S, s->machines[i].id, s->machines[i].id, ev, st->id, st->on[0].event, st->on[0].target, i, s->machines[i].id, k,
                      ev, to);
            done = 1;
        }
    }
    sb_printf(&b, "    %s_set_trace(&sys, NULL, NULL);\n}\n", S);
    sb_puts(&b, "\nint main(void) {\n    UNITY_BEGIN();\n");
    for (int i = 0; i < names.n; i++) sb_printf(&b, "    RUN_TEST(%s);\n", names.v[i]);
    sb_puts(&b, "    return UNITY_END();\n}\n");
    add(g, "router/test_router.c", &b);
}

static void gen_cmake(const SgSystem *s, GenSet *g) {
    const char *S = s->id;
    SB b;
    sb_init(&b);
    header(&b, "#");
    sb_printf(&b,
              "#\n"
              "# On a PC: cmake -S . -B build && cmake --build build && ctest --test-dir build\n"
              "# In ESP-IDF: add this folder to EXTRA_COMPONENT_DIRS. Each machine folder and\n"
              "# router/ is then a component.\n"
              "cmake_minimum_required(VERSION 3.16)\n"
              "project(%s C)\n"
              "set(CMAKE_C_STANDARD 11)\n"
              "set(CMAKE_C_STANDARD_REQUIRED ON)\n"
              "set(SG_WARNINGS -Wall -Wextra -Wswitch-enum -Werror)\n\n",
              S);
    for (int i = 0; i < s->n_machines; i++) {
        const SysMachine *sm = &s->machines[i];
        sb_printf(&b,
                  "file(GLOB %s_SOURCES ${CMAKE_CURRENT_LIST_DIR}/%s/src/gen/*.c ${CMAKE_CURRENT_LIST_DIR}/%s/src/actions/*.c\n"
                  "     ${CMAKE_CURRENT_LIST_DIR}/%s/src/services/*.c)\n"
                  "add_library(%s_%s STATIC ${%s_SOURCES})\n"
                  "target_include_directories(%s_%s PRIVATE %s/src)\n"
                  "target_compile_options(%s_%s PRIVATE ${SG_WARNINGS})\n\n",
                  sm->id, sm->dir, sm->dir, sm->dir, S, sm->id, sm->id, S, sm->id, sm->dir, S, sm->id);
    }
    sb_printf(&b, "add_library(%s_router STATIC router/%s.c router/sg_queue.c)\ntarget_compile_options(%s_router PRIVATE ${SG_WARNINGS})\ntarget_link_libraries(%s_router PUBLIC", S, S, S, S);
    for (int i = 0; i < s->n_machines; i++) sb_printf(&b, " %s_%s", S, s->machines[i].id);
    sb_printf(&b,
              ")\n\n"
              "include(FetchContent)\n"
              "if(DEFINED ENV{STATEGATE_UNITY_DIR})\n"
              "  set(FETCHCONTENT_SOURCE_DIR_UNITY $ENV{STATEGATE_UNITY_DIR})\n"
              "endif()\n"
              "FetchContent_Declare(unity\n"
              "  GIT_REPOSITORY https://github.com/ThrowTheSwitch/Unity.git\n"
              "  GIT_TAG v2.6.0\n"
              "  GIT_SHALLOW TRUE)\n"
              "FetchContent_MakeAvailable(unity)\n\n"
              "enable_testing()\n"
              "add_executable(%s_test_router router/test_router.c)\n"
              "target_link_libraries(%s_test_router PRIVATE %s_router unity)\n"
              "target_compile_options(%s_test_router PRIVATE ${SG_WARNINGS})\n"
              "add_test(NAME router COMMAND %s_test_router)\n\n"
              "# The whole system on fake boards: build/%s_sim [--trace out.sgt] <run_ms> [machine.EVENT[@ms] ...]\n"
              "add_executable(%s_sim router/sim.c)\n"
              "target_link_libraries(%s_sim PRIVATE %s_router)\n"
              "target_compile_options(%s_sim PRIVATE ${SG_WARNINGS})\n",
              S, S, S, S, S, S, S, S, S, S);
    add(g, "CMakeLists.txt", &b);

    sb_init(&b);
    header(&b, "#");
    sb_puts(&b, "# The router as an ESP-IDF component; on a PC the root CMakeLists.txt builds it.\nif(ESP_PLATFORM)\n");
    sb_printf(&b, "  idf_component_register(SRCS %s.c sg_queue.c INCLUDE_DIRS . REQUIRES freertos", S);
    for (int i = 0; i < s->n_machines; i++) sb_printf(&b, " %s", s->machines[i].dir);
    sb_puts(&b, ")\nendif()\n");
    add(g, "router/CMakeLists.txt", &b);
}

/* router/sim.c: every machine on its fake board, one clock, the real router.
 * Prints each log line as it happens and the final state of every instance;
 * --trace writes the whole run in the format `stategate trace show` and the
 * viewer read. */
static void gen_sim(const SgSystem *s, GenSet *g) {
    const char *S = s->id;
    SB b;
    sb_init(&b);
    header(&b, "/*");
    sb_printf(&b,
              "/* The %s system on a PC: every machine on its fake board, one clock, the\n"
              " * real router.\n"
              " *\n"
              " * Usage: build/%s_sim [--trace out.sgt] <run_ms> [machine.EVENT[@ms] ...]\n"
              " * Each event is posted to that machine (every instance) at its time, 0 by\n"
              " * default. The clock moves in 10 ms steps; each step runs every machine once.\n"
              " * Log lines print as they happen, then the state of every instance. */\n"
              "#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n\n#include \"%s.h\"\n",
              S, S, S);
    for (int i = 0; i < s->n_machines; i++) sb_printf(&b, "#include \"../%s/src/gen/fake.h\"\n", s->machines[i].dir);
    sb_puts(&b, "\n");
    for (int i = 0; i < s->n_machines; i++) sb_printf(&b, "static %s_probe_t %s_probe;\n", s->machines[i].id, s->machines[i].id);
    sb_printf(&b, "static %s_system_t sys;\n\n", S);
    sb_puts(&b, "typedef struct {\n    const char *name;\n    int value;\n} named_t;\n\n");
    for (int i = 0; i < s->n_machines; i++) {
        const SgModel *mm = &s->machines[i].model;
        sb_printf(&b, "static const named_t %s_events[] = {\n", s->machines[i].id);
        for (int k = 0; k < mm->events.n; k++) sb_printf(&b, "    {\"%s\", %s_EV_%s},\n", mm->events.v[k], up(s->machines[i].id), mm->events.v[k]);
        sb_puts(&b, "    {NULL, 0},\n};\n\n");
    }
    sb_puts(&b,
            "static int lookup(const named_t *t, const char *name) {\n"
            "    for (; t->name; t++)\n        if (!strcmp(t->name, name)) return t->value;\n    return -1;\n}\n\n"
            "static void trace_sink(void *ctx, const uint8_t *record, size_t len) { fwrite(record, 1, len, ctx); }\n\n"
            "typedef struct {\n    int machine, event;\n    uint64_t at;\n    int sent;\n} plan_t;\n\n");
    sb_puts(&b, "static void post(const plan_t *p) {\n    switch (p->machine) {\n");
    for (int i = 0; i < s->n_machines; i++)
        sb_printf(&b, "    case %d: %s_post_%s(&sys, (%s_event_t)p->event, NULL, 0); break;\n", i, S, s->machines[i].id, s->machines[i].id);
    sb_puts(&b, "    }\n}\n\n");
    sb_puts(&b, "/* Prints what each board logged since the last call, then clears the probes\n * so a long run never fills them. */\nstatic void drain(uint64_t t) {\n");
    for (int i = 0; i < s->n_machines; i++) {
        const char *m = s->machines[i].id;
        sb_printf(&b,
                  "    for (int i = 0; i < %s_probe.n_logs; i++) printf(\"%%8llu ms  %-8s %%s\\n\", (unsigned long long)t, %s_probe.logs[i].msg);\n"
                  "    %s_probe.n_logs = %s_probe.n_calls = %s_probe.n_traces = 0;\n",
                  m, m, m, m, m, m);
    }
    sb_puts(&b, "}\n\n");
    sb_printf(&b,
              "int main(int argc, char **argv) {\n"
              "    const char *trace_path = NULL;\n"
              "    int a = 1;\n"
              "    if (argc > 2 && !strcmp(argv[1], \"--trace\")) { trace_path = argv[2]; a = 3; }\n"
              "    if (a >= argc) {\n"
              "        fprintf(stderr, \"usage: %%s [--trace out.sgt] <run_ms> [machine.EVENT[@ms] ...]\\n\", argv[0]);\n"
              "        return 2;\n"
              "    }\n"
              "    uint64_t run_ms = strtoull(argv[a++], NULL, 10);\n"
              "    int n = argc - a;\n"
              "    plan_t *plan = calloc((size_t)(n ? n : 1), sizeof *plan);\n"
              "    for (int i = 0; i < n; i++) {\n"
              "        char buf[128];\n"
              "        snprintf(buf, sizeof buf, \"%%s\", argv[a + i]);\n"
              "        char *at = strchr(buf, '@');\n"
              "        if (at) { *at = 0; plan[i].at = strtoull(at + 1, NULL, 10); }\n"
              "        char *dot = strchr(buf, '.');\n"
              "        plan[i].machine = plan[i].event = -1;\n"
              "        if (dot) {\n"
              "            *dot = 0;\n");
    for (int i = 0; i < s->n_machines; i++)
        sb_printf(&b, "            %sif (!strcmp(buf, \"%s\")) { plan[i].machine = %d; plan[i].event = lookup(%s_events, dot + 1); }\n",
                  i ? "else " : "", s->machines[i].id, i, s->machines[i].id);
    sb_puts(&b, "        }\n"
                "        if (plan[i].event < 0) {\n"
                "            fprintf(stderr, \"%s: not machine.EVENT for a machine and event in this system\\n\", argv[a + i]);\n"
                "            return 2;\n"
                "        }\n"
                "    }\n\n");
    sb_printf(&b, "    %s_boards_t boards;\n", S);
    for (int i = 0; i < s->n_machines; i++)
        sb_printf(&b, "    boards.%s = %s_fake_hal(&%s_probe);\n", s->machines[i].id, s->machines[i].id, s->machines[i].id);
    sb_printf(&b,
              "    FILE *trace = NULL;\n"
              "    if (trace_path) {\n"
              "        trace = fopen(trace_path, \"wb\");\n"
              "        if (!trace) { perror(trace_path); return 1; }\n"
              "        uint8_t h[%s_TRACE_HEADER_SIZE];\n"
              "        fwrite(h, 1, %s_trace_header(h), trace);\n"
              "    }\n"
              "    %s_init(&sys, &boards);\n"
              "    if (trace) %s_set_trace(&sys, trace_sink, trace);\n"
              "    drain(0);\n"
              "    for (uint64_t t = 0; t <= run_ms; t += 10) {\n",
              up(S), S, S, S);
    for (int i = 0; i < s->n_machines; i++) sb_printf(&b, "        %s_probe.now_ms = t;\n", s->machines[i].id);
    sb_printf(&b,
              "        for (int i = 0; i < n; i++)\n"
              "            if (!plan[i].sent && plan[i].at <= t) { plan[i].sent = 1; post(&plan[i]); }\n"
              "        %s_step_all(&sys);\n"
              "        drain(t);\n"
              "    }\n"
              "    printf(\"after %%llu ms:\\n\", (unsigned long long)run_ms);\n",
              S);
    for (int i = 0; i < s->n_machines; i++) {
        const char *m = s->machines[i].id;
        sb_printf(&b, "    for (int i = 0; i < %s_%s_INSTANCES; i++) printf(\"  %s[%%d]  %%s\\n\", i, %s_state_id(sys.%s[i].state));\n", up(S),
                  up(m), m, m, m);
    }
    sb_puts(&b, "    if (trace) fclose(trace);\n    free(plan);\n    return 0;\n}\n");
    add(g, "router/sim.c", &b);
}

void gen_router(const SgSystem *s, GenSet *out) {
    memset(out, 0, sizeof *out);
    gen_cmake(s, out);
    gen_queue(out);
    gen_router_h(s, out);
    gen_router_c(s, out);
    gen_router_test(s, out);
    gen_sim(s, out);
}
