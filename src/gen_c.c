/* The C backend: plain C11 that builds on a PC with CMake and drops into an
 * ESP-IDF component unchanged. Same semantics as the Rust backend: the same
 * dispatch order, trace lines, tick order and generated tests. */
#include "gen_c.h"

#include <ctype.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "platform.h"

static void add(GenSet *g, const char *path, SB *content, int scaffold) {
    if (g->n == g->cap) {
        g->cap = g->cap ? g->cap * 2 : 16;
        g->v = xrealloc(g->v, sizeof(GenFile) * (size_t)g->cap);
    }
    g->v[g->n].path = xstrdup(path);
    g->v[g->n].content = content->s;
    g->v[g->n].scaffold = scaffold;
    g->n++;
}

static void header(SB *b, const SgModel *m) {
    sb_printf(b, "/* @generated by stategate from %s. Do not edit: change the model and run `stategate gen`. */\n", m->path);
}

/* Small rotating buffers so names can be used inline in one printf. */
static char *ring_put(char *s) {
    static char *ring[16];
    static int i;
    i = (i + 1) % 16;
    free(ring[i]);
    ring[i] = s;
    return s;
}

static char *upper(const char *s) {
    char *u = xstrdup(s);
    for (char *p = u; *p; p++) *p = (char)toupper((unsigned char)*p);
    return u;
}

/* posture -> POSTURE */
static const char *P(const SgModel *m) { return ring_put(upper(m->id)); }

/* posture.Calibrating -> POSTURE_STATE_CALIBRATING */
static const char *st(const SgModel *m, const char *state_id) {
    State *s = model_state(m, state_id);
    char *snake = id_to_snake(s ? s->name : "unknown");
    char *u = upper(snake);
    free(snake);
    SB b;
    sb_init(&b);
    sb_printf(&b, "%s_STATE_%s", P(m), u);
    free(u);
    return ring_put(b.s);
}

/* POWER_ON -> POSTURE_EV_POWER_ON */
static const char *ev(const SgModel *m, const char *event) {
    SB b;
    sb_init(&b);
    sb_printf(&b, "%s_EV_%s", P(m), event);
    return ring_put(b.s);
}

static const char *ctype(const char *arg) {
    if (!strcmp(arg, "u8")) return "uint8_t";
    if (!strcmp(arg, "u16")) return "uint16_t";
    if (!strcmp(arg, "u32")) return "uint32_t";
    if (!strcmp(arg, "bool")) return "bool";
    return "int32_t";
}

static const char *cmax(const char *arg) {
    if (!strcmp(arg, "u8")) return "UINT8_MAX";
    if (!strcmp(arg, "u16")) return "UINT16_MAX";
    if (!strcmp(arg, "u32")) return "UINT32_MAX";
    if (!strcmp(arg, "bool")) return "true";
    return "INT32_MAX";
}

static const Invariant *clamp_for(const SgModel *m, const char *call) {
    for (int i = 0; i < m->n_invariants; i++)
        if (m->invariants[i].kind == INV_HAL_CLAMP && !strcmp(m->invariants[i].call, call)) return &m->invariants[i];
    return NULL;
}

static const char *initial_id(const SgModel *m) {
    for (int i = 0; i < m->n_states; i++)
        if (m->states[i].initial) return m->states[i].id;
    return "?";
}

static void gen_cmake(const SgModel *m, GenSet *g) {
    SB b;
    sb_init(&b);
    sb_printf(&b, "# @generated by stategate from %s. Do not edit: change the model and run `stategate gen`.\n", m->path);
    sb_printf(&b,
              "#\n"
              "# On a PC: cmake -S . -B build && cmake --build build && ctest --test-dir build\n"
              "# In ESP-IDF: put this folder under components/; the machine and its nodes\n"
              "# build as one component (the fake HAL, tests and simulator stay out).\n"
              "cmake_minimum_required(VERSION 3.16)\n\n"
              "file(GLOB SG_SOURCES ${CMAKE_CURRENT_LIST_DIR}/src/gen/*.c ${CMAKE_CURRENT_LIST_DIR}/src/actions/*.c\n"
              "     ${CMAKE_CURRENT_LIST_DIR}/src/services/*.c)\n"
              "list(FILTER SG_SOURCES EXCLUDE REGEX \"/src/gen/fake\\\\.c$\")\n\n"
              "if(ESP_PLATFORM)\n"
              "  idf_component_register(SRCS ${SG_SOURCES} INCLUDE_DIRS src)\n"
              "  target_compile_options(${COMPONENT_LIB} PRIVATE -Wswitch-enum -Werror=switch-enum)\n"
              "  return()\n"
              "endif()\n\n"
              "project(%s C)\n"
              "set(CMAKE_C_STANDARD 11)\n"
              "set(CMAKE_C_STANDARD_REQUIRED ON)\n\n"
              "# Every (state, event) pair is a case with no default: a missing one is a\n"
              "# compile error, not a silent fall-through.\n"
              "set(SG_WARNINGS -Wall -Wextra -Wswitch-enum -Werror)\n\n"
              "add_library(%s STATIC ${SG_SOURCES} src/gen/fake.c)\n"
              "target_include_directories(%s PUBLIC src)\n"
              "target_compile_options(%s PRIVATE ${SG_WARNINGS})\n\n"
              "# Unity, the test framework ESP-IDF ships. To build offline, point the\n"
              "# STATEGATE_UNITY_DIR environment variable at a local copy of Unity v2.6.0.\n"
              "include(FetchContent)\n"
              "if(DEFINED ENV{STATEGATE_UNITY_DIR})\n"
              "  set(FETCHCONTENT_SOURCE_DIR_UNITY $ENV{STATEGATE_UNITY_DIR})\n"
              "endif()\n"
              "FetchContent_Declare(unity\n"
              "  GIT_REPOSITORY https://github.com/ThrowTheSwitch/Unity.git\n"
              "  GIT_TAG v2.6.0\n"
              "  GIT_SHALLOW TRUE)\n"
              "FetchContent_MakeAvailable(unity)\n\n"
              "enable_testing()\n"
              "file(GLOB SG_TESTS ${CMAKE_CURRENT_LIST_DIR}/tests/*.c)\n"
              "foreach(test_src ${SG_TESTS})\n"
              "  get_filename_component(name ${test_src} NAME_WE)\n"
              "  add_executable(test_${name} ${test_src})\n"
              "  target_link_libraries(test_${name} PRIVATE %s unity)\n"
              "  target_compile_options(test_${name} PRIVATE ${SG_WARNINGS})\n"
              "  add_test(NAME ${name} COMMAND test_${name})\n"
              "endforeach()\n\n"
              "add_executable(sim examples/sim.c)\n"
              "target_link_libraries(sim PRIVATE %s)\n"
              "target_compile_options(sim PRIVATE ${SG_WARNINGS})\n",
              m->id, m->id, m->id, m->id, m->id, m->id);
    add(g, "CMakeLists.txt", &b, 0);
}

static void gen_hal(const SgModel *m, GenSet *g) {
    const char *p = m->id;
    /* safe_hal.h: all node code sees. The struct is incomplete here, so a
     * node cannot reach the raw HAL behind it. */
    SB b;
    sb_init(&b);
    header(&b, m);
    sb_printf(&b,
              "/* The only HAL handle node logic receives. Locked safety limits are enforced\n"
              " * in the generated wrappers (safe_hal.c), so no action can exceed them. */\n"
              "#ifndef %s_SAFE_HAL_H\n#define %s_SAFE_HAL_H\n\n"
              "#include <stdbool.h>\n#include <stdint.h>\n\n"
              "typedef struct %s_safe_hal %s_safe_hal_t;\n\n",
              P(m), P(m), p, p);
    for (int i = 0; i < m->n_hal; i++) {
        const Invariant *c = clamp_for(m, m->hal[i].call);
        if (!c) continue;
        char *up = upper(m->hal[i].call);
        sb_printf(&b, "/* Locked by %s. */\n#define %s_%s_MAX %ld\n\n", c->id, P(m), up, c->max);
        free(up);
    }
    sb_printf(&b, "uint64_t %s_hal_now_ms(%s_safe_hal_t *hal);\nvoid %s_hal_log(%s_safe_hal_t *hal, const char *msg);\n", p, p, p, p);
    for (int i = 0; i < m->n_hal; i++)
        sb_printf(&b, "void %s_hal_%s(%s_safe_hal_t *hal, %s value);\n", p, m->hal[i].call, p, ctype(m->hal[i].arg));
    sb_puts(&b, "\n#endif\n");
    add(g, "src/gen/safe_hal.h", &b, 0);

    /* hal.h: the raw interface, for the board and the fake. Node code never
     * includes it (the gate checks). */
    sb_init(&b);
    header(&b, m);
    sb_printf(&b,
              "/* Hardware abstraction layer. Implement it once for the real board and once\n"
              " * for tests (see fake.h). Node logic never includes this header. */\n"
              "#ifndef %s_HAL_H\n#define %s_HAL_H\n\n"
              "#include \"safe_hal.h\"\n\n"
              "typedef struct {\n"
              "    void *ctx;\n"
              "    uint64_t (*now_ms)(void *ctx);\n"
              "    void (*log)(void *ctx, const char *msg);\n",
              P(m), P(m));
    for (int i = 0; i < m->n_hal; i++)
        sb_printf(&b, "    void (*%s)(void *ctx, %s value);\n", m->hal[i].call, ctype(m->hal[i].arg));
    sb_printf(&b,
              "} %s_hal_t;\n\n"
              "struct %s_safe_hal {\n    %s_hal_t inner;\n};\n\n"
              "static inline %s_safe_hal_t %s_safe_hal(%s_hal_t inner) {\n"
              "    %s_safe_hal_t s = {inner};\n    return s;\n}\n\n#endif\n",
              p, p, p, p, p, p, p);
    add(g, "src/gen/hal.h", &b, 0);

    sb_init(&b);
    header(&b, m);
    sb_printf(&b,
              "#include \"hal.h\"\n\n"
              "uint64_t %s_hal_now_ms(%s_safe_hal_t *hal) {\n    return hal->inner.now_ms(hal->inner.ctx);\n}\n\n"
              "void %s_hal_log(%s_safe_hal_t *hal, const char *msg) {\n    hal->inner.log(hal->inner.ctx, msg);\n}\n",
              p, p, p, p);
    for (int i = 0; i < m->n_hal; i++) {
        const HalCall *h = &m->hal[i];
        const Invariant *c = clamp_for(m, h->call);
        sb_printf(&b, "\n");
        if (c) {
            char *up = upper(h->call);
            sb_printf(&b, "/* @invariant %s: value is clamped to at most %ld. */\n", c->id, c->max);
            sb_printf(&b, "void %s_hal_%s(%s_safe_hal_t *hal, %s value) {\n", p, h->call, p, ctype(h->arg));
            sb_printf(&b, "    if (value > %s_%s_MAX) value = %s_%s_MAX;\n", P(m), up, P(m), up);
            free(up);
        } else {
            sb_printf(&b, "void %s_hal_%s(%s_safe_hal_t *hal, %s value) {\n", p, h->call, p, ctype(h->arg));
        }
        sb_printf(&b, "    hal->inner.%s(hal->inner.ctx, value);\n}\n", h->call);
    }
    add(g, "src/gen/safe_hal.c", &b, 0);
}

static void gen_fake(const SgModel *m, GenSet *g) {
    const char *p = m->id;
    SB b;
    sb_init(&b);
    header(&b, m);
    sb_printf(&b,
              "/* Fake hardware for tests and simulation on a PC. */\n"
              "#ifndef %s_FAKE_H\n#define %s_FAKE_H\n\n"
              "#include \"hal.h\"\n\n"
              "#define %s_FAKE_MAX 1024\n\n"
              "/* What the fake recorded, in order. Recording stops when an array is full. */\n"
              "typedef struct {\n"
              "    uint64_t now_ms;\n"
              "    struct { const char *call; int64_t value; } calls[%s_FAKE_MAX];\n"
              "    int n_calls;\n"
              "    struct { uint64_t at; char msg[160]; } logs[%s_FAKE_MAX];\n"
              "    int n_logs;\n"
              "} %s_probe_t;\n\n"
              "/* Clears the probe and returns a HAL that records into it. */\n"
              "%s_hal_t %s_fake_hal(%s_probe_t *probe);\n"
              "/* The last value passed to `call`; false if it was never called. */\n"
              "bool %s_probe_last(const %s_probe_t *probe, const char *call, int64_t *value);\n\n#endif\n",
              P(m), P(m), P(m), P(m), P(m), p, p, p, p, p, p);
    add(g, "src/gen/fake.h", &b, 0);

    sb_init(&b);
    header(&b, m);
    sb_printf(&b,
              "#include \"fake.h\"\n\n#include <stdio.h>\n#include <string.h>\n\n"
              "%s"
              "static void record(%s_probe_t *p, const char *call, int64_t value) {\n"
              "    if (p->n_calls == %s_FAKE_MAX) return;\n"
              "    p->calls[p->n_calls].call = call;\n"
              "    p->calls[p->n_calls].value = value;\n"
              "    p->n_calls++;\n"
              "}\n\n"
              "static uint64_t fake_now_ms(void *ctx) {\n    return ((%s_probe_t *)ctx)->now_ms;\n}\n\n"
              "static void fake_log(void *ctx, const char *msg) {\n"
              "    %s_probe_t *p = ctx;\n"
              "    if (p->n_logs == %s_FAKE_MAX) return;\n"
              "    p->logs[p->n_logs].at = p->now_ms;\n"
              "    snprintf(p->logs[p->n_logs].msg, sizeof p->logs[p->n_logs].msg, \"%%s\", msg);\n"
              "    p->n_logs++;\n"
              "}\n",
              m->n_hal ? "" : "__attribute__((unused)) /* this machine declares no HAL calls */\n", p, P(m), p, p, P(m));
    for (int i = 0; i < m->n_hal; i++)
        sb_printf(&b, "\nstatic void fake_%s(void *ctx, %s value) {\n    record(ctx, \"%s\", (int64_t)value);\n}\n",
                  m->hal[i].call, ctype(m->hal[i].arg), m->hal[i].call);
    sb_printf(&b,
              "\n%s_hal_t %s_fake_hal(%s_probe_t *probe) {\n"
              "    memset(probe, 0, sizeof *probe);\n"
              "    %s_hal_t h;\n"
              "    memset(&h, 0, sizeof h);\n"
              "    h.ctx = probe;\n"
              "    h.now_ms = fake_now_ms;\n"
              "    h.log = fake_log;\n",
              p, p, p, p);
    for (int i = 0; i < m->n_hal; i++) sb_printf(&b, "    h.%s = fake_%s;\n", m->hal[i].call, m->hal[i].call);
    sb_printf(&b,
              "    return h;\n}\n\n"
              "bool %s_probe_last(const %s_probe_t *probe, const char *call, int64_t *value) {\n"
              "    for (int i = probe->n_calls - 1; i >= 0; i--)\n"
              "        if (!strcmp(probe->calls[i].call, call)) {\n"
              "            *value = probe->calls[i].value;\n"
              "            return true;\n"
              "        }\n"
              "    return false;\n"
              "}\n",
              p, p);
    add(g, "src/gen/fake.c", &b, 0);
}

static void gen_machine(const SgModel *m, GenSet *g) {
    const char *p = m->id;
    SB b;
    sb_init(&b);
    header(&b, m);
    sb_printf(&b,
              "/* Machine wiring: states, events and every (state, event) pair. */\n"
              "#ifndef %s_MACHINE_H\n#define %s_MACHINE_H\n\n"
              "#include <stdbool.h>\n#include <stdint.h>\n\n"
              "#include \"safe_hal.h\"\n\n"
              "typedef enum {\n",
              P(m), P(m));
    for (int i = 0; i < m->n_states; i++) sb_printf(&b, "    %s,\n", st(m, m->states[i].id));
    sb_printf(&b, "} %s_state_t;\n#define %s_STATE_COUNT %d\n\ntypedef enum {\n", p, P(m), m->n_states);
    for (int i = 0; i < m->events.n; i++) sb_printf(&b, "    %s,\n", ev(m, m->events.v[i]));
    sb_printf(&b,
              "} %s_event_t;\n#define %s_EVENT_COUNT %d\n\n"
              "typedef enum { %s_IGNORED, %s_TRANSITION } %s_outcome_t;\n\n"
              "typedef struct {\n    %s_state_t state;\n    uint64_t entered_ms;\n} %s_machine_t;\n\n"
              "/* Starts in the initial state (%s) and runs its entry actions. */\n"
              "void %s_start(%s_machine_t *m, %s_safe_hal_t *hal);\n"
              "/* Places the machine in `state` without running any action. Used by generated tests. */\n"
              "void %s_at(%s_machine_t *m, %s_state_t state, uint64_t now_ms);\n"
              "%s_outcome_t %s_send(%s_machine_t *m, %s_event_t event, %s_safe_hal_t *hal);\n"
              "/* Advances safety watchdogs, `after` timers and invoked services, in that\n"
              " * order. Call it regularly (e.g. every 10 ms on the device). */\n"
              "void %s_tick(%s_machine_t *m, %s_safe_hal_t *hal);\n\n"
              "/* The stable node ID from the model. */\n"
              "const char *%s_state_id(%s_state_t state);\n"
              "const char *%s_event_name(%s_event_t event);\n"
              "bool %s_event_from_name(const char *name, %s_event_t *event);\n\n#endif\n",
              p, P(m), m->events.n, P(m), P(m), p, p, p, initial_id(m), p, p, p, p, p, p, p, p, p, p, p, p, p, p, p,
              p, p, p, p, p);
    add(g, "src/gen/machine.h", &b, 0);

    /* nodes.h: what the hand-written nodes implement. */
    sb_init(&b);
    header(&b, m);
    sb_printf(&b,
              "/* The hand-written nodes: one function per action, one poll per service. */\n"
              "#ifndef %s_NODES_H\n#define %s_NODES_H\n\n#include \"machine.h\"\n#include \"safe_hal.h\"\n\n",
              P(m), P(m));
    for (int i = 0; i < m->n_actions; i++) sb_printf(&b, "void %s_%s_run(%s_safe_hal_t *hal);\n", p, m->actions[i].id, p);
    for (int i = 0; i < m->n_services; i++) {
        const Service *s = &m->services[i];
        sb_puts(&b, "\n/* Called on every tick while an invoking state is active. To emit an event,\n * set *event and return true. May emit: ");
        for (int k = 0; k < s->emits.n; k++) sb_printf(&b, "%s%s", k ? ", " : "", s->emits.v[k]);
        if (!s->emits.n) sb_puts(&b, "nothing");
        sb_printf(&b, ". */\nbool %s_%s_poll(%s_safe_hal_t *hal, %s_event_t *event);\n", p, s->id, p, p);
    }
    sb_puts(&b, "\n#endif\n");
    add(g, "src/gen/nodes.h", &b, 0);

    /* machine.c */
    sb_init(&b);
    header(&b, m);
    sb_printf(&b,
              "/* Every switch lists every case and has no catch-all: the compiler, with\n"
              " * -Wswitch-enum -Werror, refuses a missing (state, event) pair. */\n"
              "#include \"machine.h\"\n\n#include <string.h>\n\n#include \"nodes.h\"\n\n"
              "const char *%s_state_id(%s_state_t state) {\n    switch (state) {\n",
              p, p);
    for (int i = 0; i < m->n_states; i++)
        sb_printf(&b, "    case %s: return \"%s\";\n", st(m, m->states[i].id), m->states[i].id);
    sb_printf(&b, "    }\n    return \"?\";\n}\n\nconst char *%s_event_name(%s_event_t event) {\n    switch (event) {\n", p, p);
    for (int i = 0; i < m->events.n; i++) sb_printf(&b, "    case %s: return \"%s\";\n", ev(m, m->events.v[i]), m->events.v[i]);
    sb_printf(&b,
              "    }\n    return \"?\";\n}\n\n"
              "bool %s_event_from_name(const char *name, %s_event_t *event) {\n"
              "    for (int i = 0; i < %s_EVENT_COUNT; i++)\n"
              "        if (!strcmp(%s_event_name((%s_event_t)i), name)) {\n"
              "            *event = (%s_event_t)i;\n"
              "            return true;\n"
              "        }\n"
              "    return false;\n"
              "}\n\n",
              p, p, P(m), p, p, p);

    /* enter / exit */
    for (int pass = 0; pass < 2; pass++) {
        sb_printf(&b, "static void %s(%s_machine_t *m, %s_safe_hal_t *hal) {\n", pass ? "run_exit" : "run_entry", p, p);
        int any = 0;
        for (int i = 0; i < m->n_states; i++) any |= (pass ? m->states[i].exit.n : m->states[i].entry.n) > 0;
        if (!any) sb_puts(&b, "    (void)hal;\n");
        sb_puts(&b, "    switch (m->state) {\n");
        for (int i = 0; i < m->n_states; i++) {
            const State *s = &m->states[i];
            const StrList *l = pass ? &s->exit : &s->entry;
            sb_printf(&b, "    case %s:\n", st(m, s->id));
            for (int k = 0; k < l->n; k++) sb_printf(&b, "        %s_%s_run(hal);\n", p, l->v[k]);
            sb_puts(&b, "        break;\n");
        }
        sb_puts(&b, "    }\n}\n\n");
    }

    sb_printf(&b,
              "void %s_start(%s_machine_t *m, %s_safe_hal_t *hal) {\n"
              "    m->state = %s;\n    m->entered_ms = %s_hal_now_ms(hal);\n    run_entry(m, hal);\n}\n\n"
              "void %s_at(%s_machine_t *m, %s_state_t state, uint64_t now_ms) {\n"
              "    m->state = state;\n    m->entered_ms = now_ms;\n}\n\n",
              p, p, p, st(m, initial_id(m)), p, p, p, p);

    /* send */
    sb_printf(&b,
              "%s_outcome_t %s_send(%s_machine_t *m, %s_event_t event, %s_safe_hal_t *hal) {\n"
              "    %s_state_t to = m->state;\n"
              "    const char *trace = NULL;\n"
              "    switch (m->state) {\n",
              p, p, p, p, p, p);
    for (int i = 0; i < m->n_states; i++) {
        const State *s = &m->states[i];
        sb_printf(&b, "    case %s:\n        switch (event) {\n", st(m, s->id));
        for (int k = 0; k < m->events.n; k++) {
            const char *e = m->events.v[k];
            const char *t = state_target(s, e);
            if (t)
                sb_printf(&b, "        case %s: to = %s; trace = \"%s --%s--> %s\"; break;\n", ev(m, e), st(m, t), s->id, e, t);
            else
                sb_printf(&b, "        case %s: return %s_IGNORED;\n", ev(m, e), P(m));
        }
        sb_puts(&b, "        }\n        break;\n");
    }
    sb_printf(&b,
              "    }\n"
              "    if (!trace) return %s_IGNORED; /* an out-of-range event value */\n"
              "    %s_hal_log(hal, trace);\n"
              "    run_exit(m, hal);\n"
              "    m->state = to;\n"
              "    m->entered_ms = %s_hal_now_ms(hal);\n"
              "    run_entry(m, hal);\n"
              "    return %s_TRANSITION;\n"
              "}\n\n",
              P(m), p, p, P(m));

    /* services */
    sb_printf(&b, "static bool poll_services(%s_machine_t *m, %s_safe_hal_t *hal, %s_event_t *out) {\n", p, p, p);
    if (!m->n_services) sb_puts(&b, "    (void)hal;\n    (void)out;\n");
    sb_puts(&b, "    switch (m->state) {\n");
    for (int i = 0; i < m->n_states; i++) {
        const State *s = &m->states[i];
        sb_printf(&b, "    case %s:\n", st(m, s->id));
        for (int k = 0; k < s->invoke.n; k++) {
            const Service *svc = model_service(m, s->invoke.v[k]);
            sb_printf(&b, "        if (%s_%s_poll(hal, out)) {\n            switch (*out) {\n", p, svc->id);
            int n_ok = 0;
            for (int x = 0; x < m->events.n; x++)
                if (sl_contains(&svc->emits, m->events.v[x])) { sb_printf(&b, "            case %s:\n", ev(m, m->events.v[x])); n_ok++; }
            if (n_ok) sb_puts(&b, "                return true;\n");
            for (int x = 0; x < m->events.n; x++)
                if (!sl_contains(&svc->emits, m->events.v[x])) sb_printf(&b, "            case %s:\n", ev(m, m->events.v[x]));
            if (n_ok < m->events.n)
                sb_printf(&b, "                %s_hal_log(hal, \"%s emitted an event it does not declare in 'emits'\");\n"
                              "                break;\n",
                          p, svc->id);
            sb_puts(&b, "            }\n        }\n");
        }
        sb_puts(&b, "        return false;\n");
    }
    sb_puts(&b, "    }\n    return false;\n}\n\n");

    /* tick */
    sb_printf(&b,
              "void %s_tick(%s_machine_t *m, %s_safe_hal_t *hal) {\n"
              "    uint64_t now = %s_hal_now_ms(hal);\n"
              "    uint64_t elapsed = now > m->entered_ms ? now - m->entered_ms : 0;\n",
              p, p, p, p);
    for (int i = 0; i < m->n_invariants; i++) {
        const Invariant *v = &m->invariants[i];
        if (v->kind != INV_MAX_TIME_IN_STATE) continue;
        sb_printf(&b,
                  "    /* @invariant %s: at most %ld ms in %s. */\n"
                  "    if (m->state == %s && elapsed >= %ld) {\n"
                  "        %s_send(m, %s, hal);\n"
                  "        return;\n"
                  "    }\n",
                  v->id, v->limit_ms, v->state, st(m, v->state), v->limit_ms, p, ev(m, v->exit_event));
    }
    sb_printf(&b, "    (void)elapsed;\n    %s_event_t event;\n    switch (m->state) {\n", p);
    for (int i = 0; i < m->n_states; i++) {
        const State *s = &m->states[i];
        sb_printf(&b, "    case %s:\n", st(m, s->id));
        if (s->has_after)
            sb_printf(&b, "        if (elapsed >= %ld) {\n            %s_send(m, %s, hal);\n            return;\n        }\n",
                      s->after_ms, p, ev(m, s->after_event));
        sb_puts(&b, "        break;\n");
    }
    sb_printf(&b, "    }\n    if (poll_services(m, hal, &event)) %s_send(m, event, hal);\n}\n", p);
    add(g, "src/gen/machine.c", &b, 0);
}

static void users_of_action(const SgModel *m, const char *id, SB *b) {
    for (int i = 0; i < m->n_states; i++) {
        if (sl_contains(&m->states[i].entry, id)) sb_printf(b, "// @node %s (entry)\n", m->states[i].id);
        if (sl_contains(&m->states[i].exit, id)) sb_printf(b, "// @node %s (exit)\n", m->states[i].id);
    }
}

static void gen_scaffolds(const SgModel *m, GenSet *g) {
    const char *p = m->id;
    for (int i = 0; i < m->n_actions; i++) {
        const Action *a = &m->actions[i];
        SB b;
        sb_init(&b);
        sb_printf(&b, "// @action %s\n", a->id);
        users_of_action(m, a->id, &b);
        sb_printf(&b, "// @stub %s\n", a->note ? a->note : "placeholder written by stategate; replace with real logic");
        sb_printf(&b, "\n#include \"gen/nodes.h\"\n\nvoid %s_%s_run(%s_safe_hal_t *hal) {\n    %s_hal_log(hal, \"%s (stub)\");\n}\n",
                  p, a->id, p, p, a->id);
        char path[512];
        snprintf(path, sizeof path, "src/actions/%s.c", a->id);
        add(g, path, &b, 1);
    }
    for (int i = 0; i < m->n_services; i++) {
        const Service *s = &m->services[i];
        SB b;
        sb_init(&b);
        sb_printf(&b, "// @service %s\n", s->id);
        for (int k = 0; k < m->n_states; k++)
            if (sl_contains(&m->states[k].invoke, s->id)) sb_printf(&b, "// @node %s (invoke)\n", m->states[k].id);
        sb_printf(&b, "// @stub %s\n", s->note ? s->note : "placeholder written by stategate; replace with real logic");
        sb_printf(&b,
                  "\n#include \"gen/nodes.h\"\n\n"
                  "bool %s_%s_poll(%s_safe_hal_t *hal, %s_event_t *event) {\n"
                  "    (void)hal;\n    (void)event;\n    return false;\n}\n",
                  p, s->id, p, p);
        char path[512];
        snprintf(path, sizeof path, "src/services/%s.c", s->id);
        add(g, path, &b, 1);
    }
}

static void test_prelude(SB *b, const SgModel *m) {
    const char *p = m->id;
    header(b, m);
    sb_printf(b,
              "/* Test names are node and event IDs joined by `__`. */\n"
              "#include \"unity.h\"\n\n#include \"gen/fake.h\"\n#include \"gen/hal.h\"\n#include \"gen/machine.h\"\n\n"
              "static %s_probe_t probe;\nstatic %s_safe_hal_t hal;\n\n"
              "void setUp(void) {\n    hal = %s_safe_hal(%s_fake_hal(&probe));\n}\n\n"
              "void tearDown(void) {}\n",
              p, p, p, p);
}

static void gen_tests(const SgModel *m, GenSet *g) {
    const char *p = m->id;
    StrList names = {0};
    SB b;
    sb_init(&b);
    test_prelude(&b, m);
    for (int i = 0; i < m->n_states; i++) {
        if (!m->states[i].initial) continue;
        char *sid = id_to_snake(m->states[i].id);
        sb_printf(&b,
                  "\n/* @covers %s (initial) */\nstatic void starts_in__%s(void) {\n"
                  "    %s_machine_t m;\n    %s_start(&m, &hal);\n    TEST_ASSERT_EQUAL_INT(%s, m.state);\n}\n",
                  m->states[i].id, sid, p, p, st(m, m->states[i].id));
        sl_pushf(&names, "starts_in__%s", sid);
        free(sid);
    }
    for (int i = 0; i < m->n_states; i++) {
        const State *s = &m->states[i];
        char *sid = id_to_snake(s->id);
        for (int k = 0; k < m->events.n; k++) {
            const char *e = m->events.v[k];
            const char *t = state_target(s, e);
            char *el = xstrdup(e);
            for (char *c = el; *c; c++) *c = (char)tolower((unsigned char)*c);
            if (t) {
                char *tid = id_to_snake(t);
                sb_printf(&b,
                          "\n/* @covers %s --%s--> %s */\nstatic void %s__%s__%s(void) {\n"
                          "    %s_machine_t m;\n    %s_at(&m, %s, 0);\n"
                          "    TEST_ASSERT_EQUAL_INT(%s_TRANSITION, %s_send(&m, %s, &hal));\n"
                          "    TEST_ASSERT_EQUAL_INT(%s, m.state);\n}\n",
                          s->id, e, t, sid, el, tid, p, p, st(m, s->id), P(m), p, ev(m, e), st(m, t));
                sl_pushf(&names, "%s__%s__%s", sid, el, tid);
                free(tid);
            } else {
                sb_printf(&b,
                          "\n/* @covers %s ignores %s */\nstatic void %s__%s__ignored(void) {\n"
                          "    %s_machine_t m;\n    %s_at(&m, %s, 0);\n"
                          "    TEST_ASSERT_EQUAL_INT(%s_IGNORED, %s_send(&m, %s, &hal));\n"
                          "    TEST_ASSERT_EQUAL_INT(%s, m.state);\n}\n",
                          s->id, e, sid, el, p, p, st(m, s->id), P(m), p, ev(m, e), st(m, s->id));
                sl_pushf(&names, "%s__%s__ignored", sid, el);
            }
            free(el);
        }
        free(sid);
    }
    sb_puts(&b, "\nint main(void) {\n    UNITY_BEGIN();\n");
    for (int i = 0; i < names.n; i++) sb_printf(&b, "    RUN_TEST(%s);\n", names.v[i]);
    sb_puts(&b, "    return UNITY_END();\n}\n");
    add(g, "tests/transitions.c", &b, 0);

    StrList inv = {0};
    sb_init(&b);
    test_prelude(&b, m);
    for (int i = 0; i < m->n_invariants; i++) {
        const Invariant *v = &m->invariants[i];
        char *vid = id_to_snake(v->id);
        if (v->kind == INV_EVERY_STATE_HANDLES) {
            for (int s = 0; s < m->n_states; s++) {
                char *sid = id_to_snake(m->states[s].id);
                sb_printf(&b,
                          "\n/* @covers %s in %s: %s --> %s */\nstatic void %s__%s(void) {\n"
                          "    %s_machine_t m;\n    %s_at(&m, %s, 0);\n"
                          "    %s_send(&m, %s, &hal);\n    TEST_ASSERT_EQUAL_INT(%s, m.state);\n}\n",
                          v->id, m->states[s].id, v->event, v->target, vid, sid, p, p, st(m, m->states[s].id), p,
                          ev(m, v->event), st(m, v->target));
                sl_pushf(&inv, "%s__%s", vid, sid);
                free(sid);
            }
        } else if (v->kind == INV_MAX_TIME_IN_STATE) {
            char *sid = id_to_snake(v->state);
            sb_printf(&b,
                      "\n/* @covers %s: %s lasts at most %ld ms */\nstatic void %s__%s_exits_by_%ld_ms(void) {\n"
                      "    %s_machine_t m;\n    %s_at(&m, %s, 0);\n"
                      "    probe.now_ms = %ld;\n    %s_tick(&m, &hal);\n"
                      "    TEST_ASSERT_NOT_EQUAL_INT(%s, m.state);\n}\n",
                      v->id, v->state, v->limit_ms, vid, sid, v->limit_ms, p, p, st(m, v->state), v->limit_ms, p,
                      st(m, v->state));
            sl_pushf(&inv, "%s__%s_exits_by_%ld_ms", vid, sid, v->limit_ms);
            free(sid);
        } else if (v->kind == INV_HAL_CLAMP) {
            const HalCall *h = model_hal(m, v->call);
            sb_printf(&b,
                      "\n/* @covers %s: %s is clamped to %ld */\nstatic void %s__%s_clamped_to_%ld(void) {\n"
                      "    int64_t last = -1;\n"
                      "    %s_hal_%s(&hal, %s);\n"
                      "    TEST_ASSERT_TRUE(%s_probe_last(&probe, \"%s\", &last));\n"
                      "    TEST_ASSERT_EQUAL_INT64(%ld, last);\n}\n",
                      v->id, v->call, v->max, vid, v->call, v->max, p, v->call, cmax(h ? h->arg : "u8"), p, v->call, v->max);
            sl_pushf(&inv, "%s__%s_clamped_to_%ld", vid, v->call, v->max);
        }
        free(vid);
    }
    sb_puts(&b, "\nint main(void) {\n    UNITY_BEGIN();\n");
    for (int i = 0; i < inv.n; i++) sb_printf(&b, "    RUN_TEST(%s);\n", inv.v[i]);
    sb_puts(&b, "    return UNITY_END();\n}\n");
    add(g, "tests/invariants.c", &b, 0);
}

static void gen_sim(const SgModel *m, GenSet *g) {
    const char *p = m->id;
    SB b;
    sb_init(&b);
    header(&b, m);
    sb_printf(&b,
              "/* Runs the machine on fake hardware and prints every log line.\n"
              " * Usage: build/sim <run_ms> [EVENT ...]\n"
              " * The listed events are sent at t = 0, in order. */\n"
              "#include <stdio.h>\n#include <stdlib.h>\n\n"
              "#include \"gen/fake.h\"\n#include \"gen/hal.h\"\n#include \"gen/machine.h\"\n\n"
              "static %s_probe_t probe;\n\n"
              "int main(int argc, char **argv) {\n"
              "    uint64_t run_ms = argc > 1 ? strtoull(argv[1], NULL, 10) : 15000;\n"
              "    %s_safe_hal_t hal = %s_safe_hal(%s_fake_hal(&probe));\n"
              "    %s_machine_t m;\n"
              "    %s_start(&m, &hal);\n"
              "    for (int i = 2; i < argc; i++) {\n"
              "        %s_event_t e;\n"
              "        if (%s_event_from_name(argv[i], &e)) %s_send(&m, e, &hal);\n"
              "        else fprintf(stderr, \"unknown event %%s\\n\", argv[i]);\n"
              "    }\n"
              "    int printed = 0;\n"
              "    for (uint64_t t = 0; t <= run_ms; t += 10) {\n"
              "        probe.now_ms = t;\n"
              "        %s_tick(&m, &hal);\n"
              "        for (; printed < probe.n_logs; printed++)\n"
              "            printf(\"%%7.1fs  %%s\\n\", (double)probe.logs[printed].at / 1000.0, probe.logs[printed].msg);\n"
              "    }\n"
              "    printf(\"final state: %%s\\n\", %s_state_id(m.state));\n"
              "    return 0;\n"
              "}\n",
              p, p, p, p, p, p, p, p, p, p, p);
    add(g, "examples/sim.c", &b, 0);
}

void gen_c(const SgModel *m, GenSet *out) {
    memset(out, 0, sizeof *out);
    gen_cmake(m, out);
    gen_hal(m, out);
    gen_fake(m, out);
    gen_machine(m, out);
    gen_tests(m, out);
    gen_sim(m, out);
    gen_scaffolds(m, out);
}

/* ---- gate checks for C projects ---- */

/* No `default:` in generated C, and no node file reaching past the safe HAL:
 * nodes include gen/nodes.h (or gen/safe_hal.h), never gen/hal.h or the fake. */
void c_check_wildcards(const GenSet *g, StrList *e) {
    for (int i = 0; i < g->n; i++) {
        const GenFile *f = &g->v[i];
        size_t n = strlen(f->path);
        int is_c = n > 2 && (!strcmp(f->path + n - 2, ".c") || !strcmp(f->path + n - 2, ".h"));
        if (!is_c) continue;
        char *disk = read_file(f->path, NULL);
        if (!disk) continue;
        int line = 1;
        for (char *p = disk; *p; p++) {
            if (*p == '\n') { line++; continue; }
            if (!f->scaffold && !strncmp(p, "default", 7) && (p == disk || !(isalnum((unsigned char)p[-1]) || p[-1] == '_'))) {
                const char *q = p + 7;
                while (*q == ' ' || *q == '\t') q++;
                if (*q == ':') sl_pushf(e, "%s:%d: 'default:' case in generated code", f->path, line);
            }
            if (f->scaffold && *p == '#' && (p == disk || p[-1] == '\n')) {
                const char *q = p + 1;
                while (*q == ' ' || *q == '\t') q++;
                if (strncmp(q, "include", 7)) continue;
                const char *open = strpbrk(q, "\"<\n");
                if (!open || *open == '\n') continue;
                const char *close = strpbrk(open + 1, "\">\n");
                if (!close || *close == '\n') continue;
                char inc[256];
                size_t len = (size_t)(close - open - 1) < sizeof inc - 1 ? (size_t)(close - open - 1) : sizeof inc - 1;
                memcpy(inc, open + 1, len);
                inc[len] = 0;
                const char *base = strrchr(inc, '/') ? strrchr(inc, '/') + 1 : inc;
                if (!strcmp(base, "hal.h") || !strcmp(base, "fake.h"))
                    sl_pushf(e, "%s:%d: node code includes %s; nodes use the safe HAL (gen/nodes.h) only", f->path, line, inc);
            }
        }
        free(disk);
    }
}

void c_run_tests(StrList *e, StrList *notes) {
    int st;
    const char *conf[] = {"cmake", "-S", ".", "-B", "build", "-DCMAKE_BUILD_TYPE=Debug", NULL};
    char *out = run_argv(conf, 1, &st);
    if (st != 0) {
        sl_pushf(e, "cmake configure failed (exit %d)", st);
        sl_push(e, out);
        free(out);
        return;
    }
    free(out);
    const char *build[] = {"cmake", "--build", "build", NULL};
    out = run_argv(build, 1, &st);
    if (st != 0) {
        sl_pushf(e, "build failed (exit %d)", st);
        int lines = 0;
        char *p = out + strlen(out);
        while (p > out && lines < 30) { p--; if (*p == '\n') lines++; }
        sl_push(e, p);
        free(out);
        return;
    }
    free(out);
    const char *test[] = {"ctest", "--test-dir", "build", "--output-on-failure", "-V", NULL};
    out = run_argv(test, 1, &st);
    /* Unity ends each test program with "N Tests M Failures K Ignored". */
    int total = 0, failed = 0;
    for (char *p = strstr(out, " Tests "); p; p = strstr(p + 1, " Tests ")) {
        char *q = p;
        while (q > out && isdigit((unsigned char)q[-1])) q--;
        int a = 0, b = 0;
        if (q < p && sscanf(q, "%d Tests %d Failures", &a, &b) == 2) { total += a; failed += b; }
    }
    if (st != 0) {
        sl_pushf(e, "ctest failed (exit %d): %d tests, %d failed", st, total, failed);
        int lines = 0;
        char *p = out + strlen(out);
        while (p > out && lines < 25) { p--; if (*p == '\n') lines++; }
        sl_push(e, p);
    } else {
        sl_pushf(notes, "%d tests passed", total);
    }
    free(out);
}
